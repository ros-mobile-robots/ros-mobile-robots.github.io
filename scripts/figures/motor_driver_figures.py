def path_through(points: Sequence[Tuple[float, float]], closed: bool = False) -> str:
    """Return an SVG path of straight pieces through points, closed with Z if closed."""
    pieces = [f'{"M" if index == 0 else "L"}{x:.1f},{y:.1f}'
              for index, (x, y) in enumerate(points)]
    return ' '.join(pieces) + (' Z' if closed else '')


def arc_points(panel: MotorPanel, radius: float, start: float,
               end: float) -> List[Tuple[float, float]]:
    """Return points along an arc around the shaft from angle start to end, ARC_STEP apart."""
    steps = max(1, math.ceil(abs(end - start) / ARC_STEP))
    return [panel.at(radius, start + (end - start) * step / steps) for step in range(steps + 1)]


def arrowhead(tip: Tuple[float, float], heading: Tuple[float, float]) -> List[Tuple[float, float]]:
    """Return the three corners of an arrowhead at tip that points along the unit heading."""
    tip_x, tip_y = tip
    along_x, along_y = heading
    base_x = tip_x - along_x * FORCE_HEAD_LENGTH
    base_y = tip_y - along_y * FORCE_HEAD_LENGTH
    return [(base_x - along_y * FORCE_HEAD_HALF_WIDTH, base_y + along_x * FORCE_HEAD_HALF_WIDTH),
            tip,
            (base_x + along_y * FORCE_HEAD_HALF_WIDTH, base_y - along_x * FORCE_HEAD_HALF_WIDTH)]


def draw_magnets(drawing: Drawing, panel: MotorPanel) -> None:
    """Add the two magnets as rings' pieces left and right of the rotor, with their poles."""
    for middle, pole in ((N_MAGNET_ANGLE, 'N'), (S_MAGNET_ANGLE, 'S')):
        start, end = middle - MAGNET_HALF_SPAN, middle + MAGNET_HALF_SPAN
        outline = (arc_points(panel, MAGNET_OUTER_RADIUS, start, end)
                   + arc_points(panel, MAGNET_INNER_RADIUS, end, start))
        drawing.line(path_through(outline, closed=True), 'magnet')
        label_x, label_y = panel.at(POLE_LABEL_RADIUS, middle)
        drawing.text(label_x, label_y + 5, pole, 'pole', 'middle')


def draw_winding_current(drawing: Drawing, panel: MotorPanel, moment: Moment) -> None:
    """Add the highlighted current from the + brush to the fed side and from the other side on.

    The current crosses from one side to the other at the far end, behind the drawing.
    """
    fed = fed_side(moment)
    other = only_one(side for side in WINDING_SIDES if side != fed)
    # Each arc runs along a segment the short way, from the brush to the link or back
    fed_link = toward(PLUS_BRUSH_ANGLE, side_angle(fed, moment) + LINK_ANGLE)
    other_link = side_angle(other, moment) + LINK_ANGLE
    into_winding = ([panel.at(LEAD_REACH, PLUS_BRUSH_ANGLE)]
                    + arc_points(panel, COMMUTATOR_RADIUS, PLUS_BRUSH_ANGLE, fed_link)
                    + [panel.at(SIDE_RADIUS, side_angle(fed, moment))])
    out_of_winding = ([panel.at(SIDE_RADIUS, side_angle(other, moment))]
                      + arc_points(panel, COMMUTATOR_RADIUS, other_link,
                                   toward(other_link, MINUS_BRUSH_ANGLE))
                      + [panel.at(LEAD_REACH, MINUS_BRUSH_ANGLE)])
    for points in (into_winding, out_of_winding):
        drawing.line(path_through(points), 'current')


def draw_commutator(drawing: Drawing, panel: MotorPanel, moment: Moment) -> None:
    """Add the two segments, each with its link to its side, and the shaft."""
    for side in WINDING_SIDES:
        dashed = ' dashed' if side.dashed else ''
        middle = segment_middle(side, moment)
        reach = 90 - SEGMENT_GAP / 2
        drawing.line(path_through(arc_points(panel, COMMUTATOR_RADIUS, middle - reach,
                                             middle + reach)), f'segment{dashed}')
        link_start = panel.at(COMMUTATOR_RADIUS, side_angle(side, moment) + LINK_ANGLE)
        drawing.line(path_through([link_start, panel.at(SIDE_RADIUS, side_angle(side, moment))]),
                     f'wire{dashed}')
    shaft_x, shaft_y = panel.shaft
    drawing.circle(shaft_x, shaft_y, SHAFT_RADIUS, 'shaft')


def draw_brushes(drawing: Drawing, panel: MotorPanel) -> None:
    """Add the + brush above the commutator and the - brush below it, each with its lead."""
    shaft_x, shaft_y = panel.shaft
    for brush_angle, sign in ((PLUS_BRUSH_ANGLE, '+'), (MINUS_BRUSH_ANGLE, '−')):
        downward = brush_angle == MINUS_BRUSH_ANGLE
        brush_top = shaft_y + COMMUTATOR_RADIUS if downward else (
            shaft_y - COMMUTATOR_RADIUS - BRUSH_LENGTH)
        lead_start = brush_top + BRUSH_LENGTH if downward else brush_top
        lead_end_x, lead_end_y = panel.at(LEAD_REACH, brush_angle)
        drawing.line(path_through([(shaft_x, lead_start), (lead_end_x, lead_end_y)]), 'wire')
        drawing.rect(shaft_x - BRUSH_WIDTH / 2, brush_top, BRUSH_WIDTH, BRUSH_LENGTH, 'brush')
        sign_y = lead_end_y + LEAD_LABEL_GAP + 9 if downward else lead_end_y - LEAD_LABEL_GAP
        drawing.text(lead_end_x, sign_y, sign, 'name strong', 'middle')


def draw_side(drawing: Drawing, panel: MotorPanel, side: WindingSide, moment: Moment) -> None:
    """Add a side of the winding: its conductor, its current's mark, its push and its name."""
    x, y = panel.at(SIDE_RADIUS, side_angle(side, moment))
    drawing.circle(x, y, CONDUCTOR_RADIUS, 'conductor')
    if current_into_page(side, moment):
        drawing.line(f'M{x - MARK_HALF_SIZE:.1f},{y - MARK_HALF_SIZE:.1f} '
                     f'L{x + MARK_HALF_SIZE:.1f},{y + MARK_HALF_SIZE:.1f} '
                     f'M{x - MARK_HALF_SIZE:.1f},{y + MARK_HALF_SIZE:.1f} '
                     f'L{x + MARK_HALF_SIZE:.1f},{y - MARK_HALF_SIZE:.1f}', 'into-page')
    else:
        drawing.circle(x, y, DOT_RADIUS, 'out-of-page')
    up = push_up(side, moment)
    heading = -1 if up else 1  # the push along the drawing's y, which grows downward
    start_y = y + heading * CONDUCTOR_RADIUS
    tip = (x, start_y + heading * FORCE_LENGTH)
    drawing.line(path_through([(x, start_y), tip]), 'force')
    drawing.line(path_through(arrowhead(tip, (0, heading)), closed=True), 'force-head')
    label_y = y + SIDE_LABEL_BELOW if up else y - SIDE_LABEL_ABOVE
    drawing.text(x, label_y, side.name, 'name strong', 'middle')


def draw_turn_arrow(drawing: Drawing, panel: MotorPanel) -> None:
    """Add the arc whose arrowhead shows the rotor turning counterclockwise."""
    points = arc_points(panel, TURN_ARROW_RADIUS, TURN_ARROW_FROM, TURN_ARROW_TO)
    drawing.line(path_through(points), 'turn')
    end = math.radians(TURN_ARROW_TO)
    # Counterclockwise on the page: the angle grows, and the drawing's y grows downward
    heading = (-math.sin(end), -math.cos(end))
    drawing.line(path_through(arrowhead(points[-1], heading), closed=True), 'turn-head')


def draw_labels(drawing: Drawing, panel: MotorPanel) -> None:
    """Add the names of a brush and of the commutator, with a line to the commutator."""
    drawing.text(*panel.offset(*BRUSH_LABEL_POSITION), 'brush', 'note')
    drawing.text(*panel.offset(*COMMUTATOR_LABEL_POSITION), 'commutator', 'note')
    drawing.line(path_through([panel.offset(*point) for point in COMMUTATOR_LEADER]), 'wire')


def fed_side_label(moment: Moment) -> str:
    """Return the line under a moment's title that names the side the + brush feeds."""
    return f"+ brush on {fed_side(moment).name}'s segment"


def draw_moment(drawing: Drawing, panel: MotorPanel, moment: Moment) -> None:
    """Add one moment: its title and line, the magnets, the commutator, the brushes and sides."""
    drawing.text(panel.middle_x, panel.top + 12, moment.title, 'name strong', 'middle')
    drawing.text(panel.middle_x, panel.top + 25, fed_side_label(moment), 'note', 'middle')
    draw_magnets(drawing, panel)
    draw_winding_current(drawing, panel, moment)
    draw_commutator(drawing, panel, moment)
    draw_brushes(drawing, panel)
    for side in WINDING_SIDES:
        draw_side(drawing, panel, side, moment)
    draw_turn_arrow(drawing, panel)
    draw_labels(drawing, panel)


def commutator_figure(layout: MotorLayout) -> str:
    """Return the SVG element of the moments' panels in a layout."""
    drawing = Drawing()
    for index, moment in enumerate(MOMENTS):
        draw_moment(drawing, layout.panel(index), moment)
    title = 'A motor with one winding, at the start and half a turn later'
    return svg_element(f'{layout.css_class}-commutator', f'ac-fig {layout.css_class}',
                       (layout.width, layout.height), title, drawing.elements, markers=())


def commutator_include() -> str:
    """Return the include of the commutator's two moments."""
    return figure_include(
        COMMUTATOR_RULES, [commutator_figure(layout) for layout in MOTOR_LAYOUTS],
        "The view looks along the shaft from the commutator's end. a and b are the two sides of "
        "one winding. Each connects to one of the commutator's two segments, and b's segment and "
        'link are dashed. Trace the highlighted current from the + brush through the segment '
        'that it touches to the side next to the N magnet. There the current runs into the page '
        "(×), and it comes back out of the page in the side next to S (•). The magnets' field, "
        'from N to S, pushes the first side down and the second up, so the rotor turns '
        'counterclockwise. Half a turn later, a and b have swapped places, and the + brush '
        "touches b's segment. The side next to N again carries the current into the page, so the "
        'push keeps turning the rotor the same way. Real motors have several windings and '
        'segments.')


# --- The H-bridge -------------------------------------------------------------------------------


class Side(Enum):
    """The two half-bridges, by their side of the motor."""

    LEFT = 'left'
    RIGHT = 'right'


class Rail(Enum):
    """The two rails that a switch can connect a motor terminal to."""

    SUPPLY = 'supply'
    GROUND = 'ground'


class Switch(NamedTuple):
    """One of the bridge's four switches: its name, its half-bridge and its rail."""

    name: str
    side: Side
    rail: Rail  # the closed switch connects the motor terminal of its side to this rail


SWITCHES = (Switch('Q1', Side.LEFT, Rail.SUPPLY), Switch('Q2', Side.LEFT, Rail.GROUND),
            Switch('Q3', Side.RIGHT, Rail.SUPPLY), Switch('Q4', Side.RIGHT, Rail.GROUND))


class Mode(NamedTuple):
    """A mode of the bridge: its name and the names of the switches that are closed."""

    name: str
    closed: FrozenSet[str]


MODES = (Mode('Forward', frozenset({'Q1', 'Q4'})),
         Mode('Reverse', frozenset({'Q2', 'Q3'})),
         Mode('Coast', frozenset()),
         Mode('Brake', frozenset({'Q2', 'Q4'})))


class Current(Enum):
    """The path that a mode's closed switches give the current."""

    LEFT_TO_RIGHT = 'from the supply through the motor, left to right, to ground'
    RIGHT_TO_LEFT = 'from the supply through the motor, right to left, to ground'
    # A loop through the motor and one rail. The motor's rotation decides the direction
    GROUND_LOOP = 'around the loop of the motor and the ground rail'
    SUPPLY_LOOP = 'around the loop of the motor and the supply rail'
    NONE = 'no closed path'


# The current for the rails of the left and the right motor terminal. Every other pair has a
# terminal that floats
CURRENT_BY_TERMINAL_RAILS: Dict[Tuple[Optional[Rail], Optional[Rail]], Current] = {
    (Rail.SUPPLY, Rail.GROUND): Current.LEFT_TO_RIGHT,
    (Rail.GROUND, Rail.SUPPLY): Current.RIGHT_TO_LEFT,
    (Rail.GROUND, Rail.GROUND): Current.GROUND_LOOP,
    (Rail.SUPPLY, Rail.SUPPLY): Current.SUPPLY_LOOP,
}


def terminal_rail(mode: Mode, side: Side) -> Optional[Rail]:
    """Return the rail that a mode connects the motor terminal of a side to.

    The result is None for a terminal that floats, with both switches of its side open.
    """
    for switch in SWITCHES:
        if switch.side is side and switch.name in mode.closed:
            return switch.rail
    return None


def current_of(mode: Mode) -> Current:
    """Return the path of the current in a mode, from the rails of the two motor terminals."""
    rails = (terminal_rail(mode, Side.LEFT), terminal_rail(mode, Side.RIGHT))
    return CURRENT_BY_TERMINAL_RAILS.get(rails, Current.NONE)


# One bridge in a panel PANEL_HEIGHT units tall: the supply rail at the top, ground at the
# bottom, the two half-bridges at the sides, and the motor between their middles
PANEL_HEIGHT = 186
PANEL_GAP = 20  # between two panels
SUPPLY_RAIL_Y = 48  # from a panel's top
GROUND_RAIL_Y = 166
SIDE_INSET = 34  # from a panel's edge to its half-bridge
MOTOR_RADIUS = 14
SWITCH_LENGTH = 16  # along its half-bridge, from its upper to its lower contact
SUPPLY_SWITCH_Y = 66  # the upper contact of a switch to the supply rail, from a panel's top
GROUND_SWITCH_Y = 124
ARROW_GAP = 10  # from the motor's circle to the tip of the current's arrowhead
ARROW_LENGTH = 6
ARROW_HALF_WIDTH = 5


class Panel(NamedTuple):
    """The place of one bridge on a drawing: its upper left corner and its width."""

    left: float
    top: float
    width: float

    def half_bridge_x(self, side: Side) -> float:
        """Return the x of the half-bridge on a side."""
        if side is Side.LEFT:
            return self.left + SIDE_INSET
        return self.left + self.width - SIDE_INSET

    def rail_y(self, rail: Rail) -> float:
        """Return the y of a rail."""
        return self.top + (SUPPLY_RAIL_Y if rail is Rail.SUPPLY else GROUND_RAIL_Y)

    def switch_y(self, switch: Switch) -> float:
        """Return the y of a switch's upper contact."""
        return self.top + (SUPPLY_SWITCH_Y if switch.rail is Rail.SUPPLY else GROUND_SWITCH_Y)

    @property
    def motor_x(self) -> float:
        """Return the x of the motor's center, the middle of the panel."""
        return self.left + self.width / 2

    @property
    def motor_y(self) -> float:
        """Return the y of the motor and of the two motor terminals."""
        return self.top + (SUPPLY_SWITCH_Y + SWITCH_LENGTH + GROUND_SWITCH_Y) / 2


class BridgeLayout(NamedTuple):
    """A layout of the modes' panels: columns per row, the drawing's width and its class."""

    columns: int
    width: float
    css_class: str

    @property
    def panel_width(self) -> float:
        """Return the width of one panel, so that a row of panels fills the drawing."""
        return (self.width - (self.columns - 1) * PANEL_GAP) / self.columns

    @property
    def rows(self) -> int:
        """Return the number of rows that the modes' panels take."""
        return math.ceil(len(MODES) / self.columns)

    def panel(self, index: int) -> Panel:
        """Return the place of the panel of the mode at index."""
        row, column = divmod(index, self.columns)
        return Panel(column * (self.panel_width + PANEL_GAP), row * (PANEL_HEIGHT + PANEL_GAP),
                     self.panel_width)


BRIDGE_LAYOUTS = (BridgeLayout(2, NARROW_WIDTH, NARROW),
                  BridgeLayout(4, NARROW_WIDTH * WIDE_STRETCH, WIDE))
BRIDGE_RULES = COMMON_RULES + (
    ('.ac-fig .rail', f'fill:none;stroke:{FG};stroke-width:2'),
    ('.ac-fig .wire', f'fill:none;stroke:{FG_LIGHT};stroke-width:1.4'),
    ('.ac-fig .switch', f'fill:none;stroke:{FG_LIGHT};stroke-width:1.6;stroke-linecap:round'),
    ('.ac-fig .switch.closed', f'stroke:{FG};stroke-width:2.2'),
    ('.ac-fig .contact', f'fill:{BG};stroke:{FG};stroke-width:1.2'),
    ('.ac-fig .motor', f'fill:{BG};stroke:{FG};stroke-width:1.6'),
    ('.ac-fig .current', 'fill:none;stroke:var(--ac-current);stroke-width:6;opacity:.45;'
                         'stroke-linejoin:round'),
    ('.ac-fig .current-head', 'fill:var(--ac-current)'),
)


def current_path(panel: Panel, current: Current) -> str:
    """Return the SVG path of a current through the closed switches and the motor."""
    left_x = panel.half_bridge_x(Side.LEFT)
    right_x = panel.half_bridge_x(Side.RIGHT)
    if current in (Current.GROUND_LOOP, Current.SUPPLY_LOOP):
        rail_y = panel.rail_y(Rail.GROUND if current is Current.GROUND_LOOP else Rail.SUPPLY)
        return f'M{left_x:g},{panel.motor_y:g} H{right_x:g} V{rail_y:g} H{left_x:g} Z'
    start_x, end_x = (left_x, right_x) if current is Current.LEFT_TO_RIGHT else (right_x, left_x)
    return (f'M{start_x:g},{panel.rail_y(Rail.SUPPLY):g} V{panel.motor_y:g} H{end_x:g} '
            f'V{panel.rail_y(Rail.GROUND):g}')


def arrowhead_path(panel: Panel, current: Current) -> str:
    """Return the SVG path of the arrowhead beside the motor, on the side the current leaves."""
    heading = 1 if current is Current.LEFT_TO_RIGHT else -1
    tip_x = panel.motor_x + heading * (MOTOR_RADIUS + ARROW_GAP)
    base_x = tip_x - heading * ARROW_LENGTH
    return (f'M{base_x:g},{panel.motor_y - ARROW_HALF_WIDTH:g} L{tip_x:g},{panel.motor_y:g} '
            f'L{base_x:g},{panel.motor_y + ARROW_HALF_WIDTH:g} Z')


def draw_current(drawing: Drawing, panel: Panel, current: Current) -> None:
    """Add the highlighted path of a current, with an arrowhead if it has one direction."""
    if current is Current.NONE:
        return
    drawing.line(current_path(panel, current), 'current')
    if current in (Current.LEFT_TO_RIGHT, Current.RIGHT_TO_LEFT):
        drawing.line(arrowhead_path(panel, current), 'current-head')


def draw_rails_and_wires(drawing: Drawing, panel: Panel) -> None:
    """Add the two rails with their names, the half-bridges' wires and the motor's wires."""
    left_x = panel.half_bridge_x(Side.LEFT)
    right_x = panel.half_bridge_x(Side.RIGHT)
    supply_y = panel.rail_y(Rail.SUPPLY)
    ground_y = panel.rail_y(Rail.GROUND)
    for rail_y in (supply_y, ground_y):
        drawing.line(f'M{left_x:g},{rail_y:g} H{right_x:g}', 'rail')
    drawing.text(panel.motor_x, supply_y - 5, '+V', 'note', 'middle')
    drawing.text(panel.motor_x, ground_y + 13, 'GND', 'note', 'middle')
    supply_switch_y = panel.top + SUPPLY_SWITCH_Y
    ground_switch_y = panel.top + GROUND_SWITCH_Y
    for half_bridge_x in (left_x, right_x):
        drawing.line(f'M{half_bridge_x:g},{supply_y:g} V{supply_switch_y:g} '
                     f'M{half_bridge_x:g},{supply_switch_y + SWITCH_LENGTH:g} '
                     f'V{ground_switch_y:g} '
                     f'M{half_bridge_x:g},{ground_switch_y + SWITCH_LENGTH:g} V{ground_y:g}',
                     'wire')
    drawing.line(f'M{left_x:g},{panel.motor_y:g} H{panel.motor_x - MOTOR_RADIUS:g} '
                 f'M{panel.motor_x + MOTOR_RADIUS:g},{panel.motor_y:g} H{right_x:g}', 'wire')


def draw_switch(drawing: Drawing, panel: Panel, switch: Switch, closed: bool) -> None:
    """Add a switch: two contacts, a lever that touches the lower one when closed, its name."""
    x = panel.half_bridge_x(switch.side)
    upper_y = panel.switch_y(switch)
    lower_y = upper_y + SWITCH_LENGTH
    # An open lever points toward the motor, away from the switch's name
    toward_motor = 1 if switch.side is Side.LEFT else -1
    lever_end_x = x if closed else x + toward_motor * 9
    lever_end_y = lower_y if closed else lower_y - 5
    drawing.line(f'M{x:g},{upper_y:g} L{lever_end_x:g},{lever_end_y:g}',
                 'switch closed' if closed else 'switch')
    for contact_y in (upper_y, lower_y):
        drawing.circle(x, contact_y, 2, 'contact')
    drawing.text(x - toward_motor * 8, upper_y + SWITCH_LENGTH / 2 + 4, switch.name, 'note',
                 'end' if switch.side is Side.LEFT else 'start')


def closed_switches_label(mode: Mode) -> str:
    """Return the line under a mode's name that says which switches are closed."""
    if not mode.closed:
        return 'all open'
    return f'{listed(sorted(mode.closed))} closed'


def draw_mode(drawing: Drawing, panel: Panel, mode: Mode) -> None:
    """Add one bridge in one mode, with the mode's name and its closed switches above it."""
    drawing.text(panel.motor_x, panel.top + 12, mode.name, 'name strong', 'middle')
    drawing.text(panel.motor_x, panel.top + 25, closed_switches_label(mode), 'note', 'middle')
    draw_current(drawing, panel, current_of(mode))
    draw_rails_and_wires(drawing, panel)
    for switch in SWITCHES:
        draw_switch(drawing, panel, switch, switch.name in mode.closed)
    drawing.circle(panel.motor_x, panel.motor_y, MOTOR_RADIUS, 'motor')
    drawing.text(panel.motor_x, panel.motor_y + 4, 'M', 'name', 'middle')


def h_bridge_figure(layout: BridgeLayout) -> str:
    """Return the SVG element of the modes' panels in a layout's grid."""
    drawing = Drawing()
    for index, mode in enumerate(MODES):
        draw_mode(drawing, layout.panel(index), mode)
    height = layout.rows * PANEL_HEIGHT + (layout.rows - 1) * PANEL_GAP
    title = f'Current paths in {NUMBER_WORDS[len(MODES)]} H-bridge modes'
    return svg_element(f'{layout.css_class}-bridge', f'ac-fig {layout.css_class}',
                       (layout.width, height), title, drawing.elements, markers=())


def h_bridge_include() -> str:
    """Return the include of the H-bridge's modes."""
    return figure_include(
        BRIDGE_RULES, [h_bridge_figure(layout) for layout in BRIDGE_LAYOUTS],
        'Trace the highlighted path from +V through the motor M to ground in Forward and '
        'Reverse. The arrowheads show that the current passes the motor in opposite '
        'directions. In Coast, all four switches are open and no path is closed, so the motor '
        'coasts to a stop. In Brake, the two lower switches and the ground rail form a loop '
        'with the motor. A spinning motor drives a current around that loop and slows down.')


# --- PWM ----------------------------------------------------------------------------------------

# Remo's firmware passes a command's magnitude, from 0 to 2^PWM_BITS - 1, to
# Adafruit_DCMotor::setSpeed(), which sets the PWM channel of the FeatherWing's PCA9685 to
# COUNTS_PER_STEP counts per step of the command, of COUNTS_PER_PERIOD counts per period
# (Adafruit Motor Shield V2 Library 1.1.4). The firmware asks for REQUESTED_FREQUENCY_HZ. The
# library multiplies the request by LIBRARY_FREQUENCY_FACTOR and rounds the chip's prescaler
# (Adafruit_MS_PWMServoDriver::setPWMFreq()), and the PCA9685 divides its typical 25 MHz clock by
# COUNTS_PER_PERIOD times the prescaler plus 1 (its datasheet, section 7.3.5)
PWM_BITS = 8
MAX_COMMAND = 2 ** PWM_BITS - 1
COUNTS_PER_STEP = 16
COUNTS_PER_PERIOD = 4096
REQUESTED_FREQUENCY_HZ = 1600
LIBRARY_FREQUENCY_FACTOR = 0.9
OSCILLATOR_HZ = 25_000_000
COMMANDS = (64, 128, 192)
REMO_CELLS = 8
NIMH_NOMINAL_CELL_VOLTAGE = 1.2
SUPPLY_VOLTAGE = REMO_CELLS * NIMH_NOMINAL_CELL_VOLTAGE
PERIODS = 3  # that a row shows

PLOT_LEFT = 90  # the waveforms start here, after the row's label
PLOT_RIGHT_MARGIN = 12
LABEL_GAP = 10  # from a row's label to its waveform
ROW_TOP = 18
ROW_HEIGHT = 80
WAVE_HEIGHT = 40  # the supply voltage, in units
LEVEL_LABEL_GAP = 6  # from the wave to the label of a voltage level above it
BELOW_WAVE_DROP = 16  # from the bottom of a row's wave to the baseline of a text below it
PERIOD_BRACKET_RISE = 12  # from the bottom of the last row to the bracket under one period
PERIOD_LABEL_DROP = 14
BOTTOM_MARGIN = 30
PWM_RULES = COMMON_RULES + (
    ('.ac-fig .wave', f'fill:none;stroke:{FG};stroke-width:1.8'),
    ('.ac-fig .average', 'fill:none;stroke:var(--ac-current);stroke-width:1.8;'
                         'stroke-dasharray:5 3'),
    # In the text's color: the accent color on the page's background has too little contrast
    # for small text. The dashed line carries the color
    ('.ac-fig .average-label', 'font-size:11px;font-weight:700'),
    ('.ac-fig .dimension', f'fill:none;stroke:{FG_LIGHT};stroke-width:1'),
    ('.ac-fig .symbol', 'font-family:KaTeX_Math,"Times New Roman",serif;font-style:italic;'
                        'font-size:12.5px'),
)


class Pulse(NamedTuple):
    """One command's PWM counts, its duty cycle and the average voltage that it gives."""

    command: int
    counts: int  # of COUNTS_PER_PERIOD, during which the voltage is on
    duty: float  # from 0 to 1
    average: float  # in V


def pulse_of(command: int) -> Pulse:
    """Return the counts, the duty cycle and the ideal average voltage of a command."""
    counts = abs(command) * COUNTS_PER_STEP
    duty = counts / COUNTS_PER_PERIOD
    return Pulse(command, counts, duty, duty * SUPPLY_VOLTAGE)


def pulses() -> Tuple[Pulse, ...]:
    """Return the pulse of each command in COMMANDS."""
    return tuple(pulse_of(command) for command in COMMANDS)


def volts(value: float) -> str:
    """Return a voltage with one decimal."""
    return f'{value:.1f} V'


def percent(share: float) -> str:
    """Return a share from 0 to 1 in percent, with one decimal where it has one."""
    return f'{round(share * 100, 1):g} %'


def library_frequency_hz() -> float:
    """Return the frequency that Adafruit's library computes the prescaler for."""
    return REQUESTED_FREQUENCY_HZ * LIBRARY_FREQUENCY_FACTOR


def prescaler_before_rounding() -> float:
    """Return the prescaler value that Adafruit's library calculates, before it rounds it."""
    return OSCILLATOR_HZ / COUNTS_PER_PERIOD / library_frequency_hz() - 1


def prescaler() -> int:
    """Return the prescaler that Adafruit's library writes to the PCA9685."""
    return math.floor(prescaler_before_rounding() + 0.5)


def frequency_hz() -> float:
    """Return the nominal PWM frequency of the PCA9685 with this prescaler."""
    return OSCILLATOR_HZ / (COUNTS_PER_PERIOD * (prescaler() + 1))


def period_ms() -> float:
    """Return the nominal PWM period in ms."""
    return 1000 / frequency_hz()


class PwmLayout(NamedTuple):
    """A layout of the waveforms: the drawing's width and its class."""

    width: float
    css_class: str

    @property
    def plot_right(self) -> float:
        """Return the x where the waveforms end."""
        return self.width - PLOT_RIGHT_MARGIN

    @property
    def period_width(self) -> float:
        """Return the width of one period."""
        return (self.plot_right - PLOT_LEFT) / PERIODS


PWM_LAYOUTS = (PwmLayout(NARROW_WIDTH, NARROW), PwmLayout(NARROW_WIDTH * WIDE_STRETCH, WIDE))


def wave_path(layout: PwmLayout, top: float, duty: float) -> str:
    """Return the SVG path of PERIODS periods of the voltage, high for duty of each period."""
    low_y = top + WAVE_HEIGHT
    commands: List[str] = [f'M{PLOT_LEFT:g},{low_y:g}']
    for index in range(PERIODS):
        start_x = PLOT_LEFT + index * layout.period_width
        commands.append(f'V{top:g} H{start_x + duty * layout.period_width:g} V{low_y:g} '
                        f'H{start_x + layout.period_width:g}')
    return ' '.join(commands)


def draw_pulse_row(drawing: Drawing, layout: PwmLayout, top: float, pulse: Pulse) -> None:
    """Add one row: its label, the voltage's periods and the average as a dashed line."""
    low_y = top + WAVE_HEIGHT
    drawing.text(PLOT_LEFT - LABEL_GAP, top + 14, percent(pulse.duty), 'name strong', 'end')
    drawing.text(PLOT_LEFT - LABEL_GAP, top + 28, f'command {pulse.command}', 'note', 'end')
    drawing.line(wave_path(layout, top, pulse.duty), 'wave')
    average_y = low_y - pulse.duty * WAVE_HEIGHT
    drawing.line(f'M{PLOT_LEFT:g},{average_y:g} H{layout.plot_right:g}', 'average')
    drawing.text(layout.plot_right, low_y + BELOW_WAVE_DROP, f'average {volts(pulse.average)}',
                 'average-label', 'end')


def draw_level_labels(drawing: Drawing, layout: PwmLayout, top: float, pulse: Pulse) -> None:
    """Add the two voltage levels of a row: the supply over its first pulse, 0 V under its gap."""
    pulse_end_x = PLOT_LEFT + pulse.duty * layout.period_width
    drawing.text((PLOT_LEFT + pulse_end_x) / 2, top - LEVEL_LABEL_GAP, volts(SUPPLY_VOLTAGE),
                 'note', 'middle')
    drawing.text((pulse_end_x + PLOT_LEFT + layout.period_width) / 2,
                 top + WAVE_HEIGHT + BELOW_WAVE_DROP, '0 V', 'note', 'middle')


def draw_period(drawing: Drawing, layout: PwmLayout, y: float) -> None:
    """Add a bracket under the first period at y, with the period's symbol and its length."""
    end_x = PLOT_LEFT + layout.period_width
    drawing.line(f'M{PLOT_LEFT:g},{y:g} H{end_x:g} M{PLOT_LEFT:g},{y - 3:g} V{y + 3:g} '
                 f'M{end_x:g},{y - 3:g} V{y + 3:g}', 'dimension')
    # The italic symbol leans to the right, so the text after it starts a little later
    drawing.text_markup((PLOT_LEFT + end_x) / 2, y + PERIOD_LABEL_DROP,
                        'One period <tspan class="symbol">T</tspan>'
                        f'<tspan dx="1.5"> ≈ {period_ms():.2f} ms</tspan>', 'note', 'middle')


def pwm_figure(layout: PwmLayout) -> str:
    """Return the SVG element of one row of waveforms for each command, in a layout."""
    rows = pulses()
    drawing = Drawing()
    for index, pulse in enumerate(rows):
        draw_pulse_row(drawing, layout, ROW_TOP + index * ROW_HEIGHT, pulse)
    draw_level_labels(drawing, layout, ROW_TOP, rows[0])
    rows_bottom = ROW_TOP + len(rows) * ROW_HEIGHT
    draw_period(drawing, layout, rows_bottom - PERIOD_BRACKET_RISE)
    title = f'Motor voltage at {NUMBER_WORDS[len(rows)]} PWM duty cycles'
    return svg_element(f'{layout.css_class}-pwm', f'ac-fig {layout.css_class}',
                       (layout.width, rows_bottom + BOTTOM_MARGIN), title, drawing.elements,
                       markers=())


def pwm_include() -> str:
    """Return the include of the duty cycles."""
    rows = pulses()
    return figure_include(
        PWM_RULES, [pwm_figure(layout) for layout in PWM_LAYOUTS],
        f'Compare one period in each row. With an ideal supply of {volts(SUPPLY_VOLTAGE)} and '
        f'ideal switches, the commands {listed([str(pulse.command) for pulse in rows])} apply '
        f'the voltage for {listed([percent(pulse.duty) for pulse in rows])} of the period. '
        f'The dashed lines show the averages, '
        f'{listed([volts(pulse.average) for pulse in rows])}. '
        f'The example period lasts about {period_ms():.2f} ms.')


