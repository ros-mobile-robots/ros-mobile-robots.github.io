"""Generate the power flow figures on docs/power-supply.md.

Both are inline SVG that follows the site's light and dark colors:

- includes/power-supply-flow-diffbot.html: DiffBot's two supplies and the parts on them. It has
  the styles for both figures;
- includes/power-supply-flow-remo.html: Remo's two supplies and the parts on them.

A thick line is a supply, in the color of its source, with its voltage next to it. A dashed line is
a data connection. A figure draws a supply only where it is checked on the robot or in the board's
schematic. On Remo, the camera has only its documented data connection, and its box says that its
supply isn't checked. DiffBot's figure leaves out every part whose supply isn't checked. It has no
legend: its caption names the two colors.

Run from the repository root after changing a figure:

    python3 scripts/figures/power_supply_figures.py
"""

from enum import Enum
from typing import NamedTuple
from typing import Sequence

from board_drawings import Drawing
from board_drawings import escape
from board_drawings import style_element

GENERATED_COMMENT = ('<!-- Generated by scripts/figures/power_supply_figures.py. '
                     'Change the script and run it. -->\n')


class Source(Enum):
    """The source of a supply. The value is the CSS class of the source's color."""

    BANK = 'bank'
    BATTERY = 'battery'


class LineKind(Enum):
    """What a line of a figure shows. The value is the line's CSS class."""

    BANK_SUPPLY = Source.BANK.value
    BATTERY_SUPPLY = Source.BATTERY.value
    DATA = 'data'
    GROUND = 'ground'


class LegendEntry(NamedTuple):
    """A legend entry: the kind of its line sample and what such a line means."""

    kind: LineKind
    meaning: str


class TextLine(NamedTuple):
    """A line of text in a box: the text and its CSS class."""

    text: str
    css_class: str


class Box(NamedTuple):
    """A box on a figure, in pixels: its top left corner, its width and its height."""

    x: float
    y: float
    width: float
    height: float

    @property
    def right(self) -> float:
        """Return the x coordinate of the box's right edge."""
        return self.x + self.width

    @property
    def bottom(self) -> float:
        """Return the y coordinate of the box's lower edge."""
        return self.y + self.height


WIDTH = 360
# The parts on the power bank are in the left column, the motor battery's parts in the right one
LEFT_X = 10
LEFT_WIDTH = 140
RIGHT_X = 206
RIGHT_WIDTH = 144
# Remo's LiDAR and camera are in a column between the two, above the motor driver
DEVICE_X = 190
DEVICE_WIDTH = 136

POWER_BANK_BOX = Box(x=LEFT_X, y=6, width=LEFT_WIDTH, height=38)
RASPBERRY_PI_BOX = Box(x=LEFT_X, y=70, width=LEFT_WIDTH, height=60)
MCU_BOX = Box(x=LEFT_X, y=186, width=LEFT_WIDTH, height=54)
# The MCU's sensors stand side by side below the MCU
ENCODERS_BOX = Box(x=LEFT_X, y=290, width=68, height=38)
IMU_BOX = Box(x=LEFT_X + 72, y=290, width=68, height=38)
LIDAR_BOX = Box(x=DEVICE_X, y=62, width=DEVICE_WIDTH, height=36)
CAMERA_BOX = Box(x=DEVICE_X, y=104, width=DEVICE_WIDTH, height=36)
BATTERY_BOX = Box(x=RIGHT_X, y=6, width=RIGHT_WIDTH, height=38)
# The motor driver's box has its top where a figure puts it, the motors' box is this far below it
DRIVER_HEIGHT = 54
MOTORS_GAP = 50
MOTORS_HEIGHT = 38

# The supply lines of the left column leave their box this far from its left edge
LEFT_SUPPLY_OFFSET = 50
# The battery's supply line runs down the right column's right side, past the LiDAR and the camera
BATTERY_LINE_X = BATTERY_BOX.right - 12
# The supply line from the motor driver to the motors runs down the middle of the right column
MOTOR_LINE_X = RIGHT_X + RIGHT_WIDTH / 2
# The motor driver's logic lines from the MCU, 3.3 V, I2C and ground, are this far apart
LOGIC_LINE_GAP = 15
# The baselines of two text lines are this far apart, as in a box of Drawing.box()
TEXT_LINE_GAP = 14
# The baselines of two legend rows are this far apart
LEGEND_ROW_GAP = 15
# A text's baseline is this far below the middle of the text's line
BASELINE_DROP = 4
# The supply and the data line of one cable run side by side, this far apart
PAIR_GAP = 7
# A supply line ends this far before the part it feeds, and its arrowhead's tip closes the gap
HEAD_TIP = 5

USB_VOLTAGE = '5 V'
LOGIC_VOLTAGE = '3.3 V'
# Both robots run their motors on the same battery: eight NiMH AA cells of 1.2 V nominal
CELL_COUNT = 'eight'
BATTERY_VOLTAGE = '9.6 V'
BATTERY_NAME = f'{CELL_COUNT.capitalize()} NiMH AA cells'

LEGEND_BANK = LegendEntry(LineKind.BANK_SUPPLY,
                          f'supply from the power bank ({USB_VOLTAGE}, {LOGIC_VOLTAGE})')
LEGEND_BATTERY = LegendEntry(LineKind.BATTERY_SUPPLY,
                             f'supply from the motor battery ({BATTERY_VOLTAGE})')
LEGEND_DATA = LegendEntry(LineKind.DATA, 'data connection')
LEGEND_GROUND = LegendEntry(LineKind.GROUND, 'ground wire (GND)')

FG = 'var(--md-default-fg-color)'
FG_LIGHT = 'var(--md-default-fg-color--light)'
RULES = (
    ('.md-typeset figure.pf-figure', 'margin:1em auto;width:100%;max-width:480px'),
    ('.pf-fig', 'width:100%;height:auto;--pf-bank:#1e63c4;--pf-battery:#b45309;'
                'font-family:var(--md-text-font-family,Roboto),sans-serif'),
    ('[data-md-color-scheme=slate] .pf-fig', '--pf-bank:#82b1ff;--pf-battery:#ffab70'),
    ('.pf-fig text', f'fill:{FG};font-size:11px'),
    ('.pf-fig .part', f'fill:var(--md-default-bg-color);stroke:{FG_LIGHT};stroke-width:1'),
    ('.pf-fig .source', 'fill:var(--md-code-bg-color);stroke-width:2'),
    ('.pf-fig .source.bank', 'stroke:var(--pf-bank)'),
    ('.pf-fig .source.battery', 'stroke:var(--pf-battery)'),
    ('.pf-fig .line', 'fill:none'),
    ('.pf-fig .line.bank', 'stroke:var(--pf-bank);stroke-width:3'),
    ('.pf-fig .line.battery', 'stroke:var(--pf-battery);stroke-width:3'),
    ('.pf-fig .line.data', f'stroke:{FG_LIGHT};stroke-width:1.3;stroke-dasharray:4 3'),
    ('.pf-fig .line.ground', f'stroke:{FG_LIGHT};stroke-width:1.3'),
    ('.pf-fig .head-bank', 'fill:var(--pf-bank)'),
    ('.pf-fig .head-battery', 'fill:var(--pf-battery)'),
    ('.pf-fig .name', 'font-size:12px'),
    ('.pf-fig .note', f'font-size:11px;fill:{FG_LIGHT}'),
    ('.pf-fig .volt-bank', 'fill:var(--pf-bank);font-weight:700'),
    ('.pf-fig .volt-battery', 'fill:var(--pf-battery);font-weight:700'),
)


def baseline_between(top: float, bottom: float) -> float:
    """Return the baseline of a text line that is centered between the heights top and bottom."""
    return (top + bottom) / 2 + BASELINE_DROP


class Figure(Drawing):
    """Collect the SVG elements of one figure: its boxes, its lines and its legend."""

    def __init__(self, name: str, height: int, title: str) -> None:
        super().__init__()
        self.name = name
        self.height = height
        self.title = title

    def labeled_box(self, box: Box, css_class: str, lines: Sequence[TextLine]) -> None:
        """Add the box with its text lines centered in it."""
        self.box(box.x, box.y, box.width, box.height, css_class, lines)

    def wire(self, path: str, kind: LineKind) -> None:
        """Add a line of the given kind along an SVG path, without an arrowhead."""
        self.line(path, f'line {kind.value}')

    def supply(self, path: str, source: Source) -> None:
        """Add a supply line with an arrowhead toward the part it feeds.

        The arrowhead's tip is HEAD_TIP px beyond the path's end.
        """
        self.elements.append(f'<path class="line {source.value}" d="{path}" '
                             f'marker-end="url(#{self.name}-{source.value}-head)"/>')

    def legend(self, y: float, entries: Sequence[LegendEntry]) -> None:
        """Add the legend's rows below y: a sample of each line and what it means."""
        for row, entry in enumerate(entries):
            baseline = y + LEGEND_ROW_GAP * row
            self.wire(f'M{LEFT_X},{baseline - 3.5} H{LEFT_X + 26}', entry.kind)
            self.text(LEFT_X + 34, baseline, entry.meaning)

    def svg(self) -> str:
        """Return the figure as an SVG element."""
        # Not svg_element() of board_drawings: it defines one arrowhead, and each source's supply
        # lines here end in an arrowhead of the source's color
        heads = ''.join(
            f'<marker id="{self.name}-{source.value}-head" viewBox="0 0 10 10" '
            f'refX="{10 - HEAD_TIP}" refY="5" markerUnits="userSpaceOnUse" markerWidth="10" '
            f'markerHeight="10" orient="auto"><path class="head-{source.value}" '
            'd="M0,0 L10,5 L0,10 z"/></marker>'
            for source in Source)
        return (f'<svg class="pf-fig" viewBox="0 0 {WIDTH} {self.height}" role="img" '
                f'aria-labelledby="{self.name}-title"><title id="{self.name}-title">'
                f'{escape(self.title)}</title><defs>{heads}</defs>\n'
                + '\n'.join(self.elements) + '\n</svg>')


def draw_power_bank_and_pi(figure: Figure) -> None:
    """Add the power bank and the Raspberry Pi on it."""
    figure.labeled_box(POWER_BANK_BOX, 'source bank', [TextLine('USB power bank', 'name')])
    supply_x = POWER_BANK_BOX.x + LEFT_SUPPLY_OFFSET
    figure.supply(f'M{supply_x},{POWER_BANK_BOX.bottom} V{RASPBERRY_PI_BOX.y - HEAD_TIP}',
                  Source.BANK)
    figure.text(supply_x + 9, baseline_between(POWER_BANK_BOX.bottom, RASPBERRY_PI_BOX.y),
                f'{USB_VOLTAGE}, USB-C', 'volt-bank')
    figure.labeled_box(RASPBERRY_PI_BOX, 'part', [TextLine('Raspberry Pi 4 B', 'name')])


def draw_lidar_and_camera(figure: Figure) -> None:
    """Add the LiDAR and the camera on the Raspberry Pi.

    The LiDAR's USB adapter gets the supply and the data over one cable. The camera has a data
    line only, and its box says that its supply isn't checked.
    """
    pi_edge = RASPBERRY_PI_BOX.right
    lidar_supply_y = LIDAR_BOX.y + 17
    figure.supply(f'M{pi_edge},{lidar_supply_y} H{LIDAR_BOX.x - HEAD_TIP}', Source.BANK)
    figure.wire(f'M{pi_edge},{lidar_supply_y + PAIR_GAP} H{LIDAR_BOX.x}', LineKind.DATA)
    figure.text((pi_edge + LIDAR_BOX.x) / 2, lidar_supply_y - 6, USB_VOLTAGE, 'volt-bank',
                'middle')
    figure.labeled_box(LIDAR_BOX, 'part',
                       [TextLine('RPLidar A2 M8', 'name'), TextLine('USB adapter', 'note')])
    figure.wire(f'M{pi_edge},{CAMERA_BOX.y + 16} H{CAMERA_BOX.x}', LineKind.DATA)
    figure.labeled_box(CAMERA_BOX, 'part', [TextLine('Raspberry Pi Camera', 'name'),
                                            TextLine('supply not checked', 'note')])


def draw_battery_and_motors(figure: Figure, battery: Sequence[TextLine], voltage: str,
                            driver: Sequence[TextLine], driver_y: float) -> None:
    """Add the motor battery, the motor driver on it and the motors.

    battery and driver are the lines of text in the battery's and the motor driver's box,
    voltage is the battery's nominal voltage, and driver_y is the top of the motor driver's box.
    """
    driver_box = Box(x=RIGHT_X, y=driver_y, width=RIGHT_WIDTH, height=DRIVER_HEIGHT)
    motors_box = Box(x=RIGHT_X, y=driver_box.bottom + MOTORS_GAP, width=RIGHT_WIDTH,
                     height=MOTORS_HEIGHT)
    figure.labeled_box(BATTERY_BOX, 'source battery', battery)
    figure.supply(f'M{BATTERY_LINE_X},{BATTERY_BOX.bottom} V{driver_box.y - HEAD_TIP}',
                  Source.BATTERY)
    figure.text(BATTERY_LINE_X - 8, driver_box.y - 20, voltage, 'volt-battery', 'end')
    figure.labeled_box(driver_box, 'part', driver)
    figure.supply(f'M{MOTOR_LINE_X},{driver_box.bottom} V{motors_box.y - HEAD_TIP}',
                  Source.BATTERY)
    label_y = baseline_between(driver_box.bottom, motors_box.y)
    figure.text(MOTOR_LINE_X - 8, label_y - TEXT_LINE_GAP / 2, 'switched on and off',
                'volt-battery', 'end')
    figure.text(MOTOR_LINE_X - 8, label_y + TEXT_LINE_GAP / 2, 'by the driver (PWM)',
                'volt-battery', 'end')
    figure.labeled_box(motors_box, 'part', [TextLine('Two DG01D-E motors', 'name')])


def draw_mcu(figure: Figure) -> None:
    """Add the microcontroller (MCU), a Teensy, on a USB port of the Raspberry Pi.

    One USB cable carries the MCU's supply and its data.
    """
    supply_x = RASPBERRY_PI_BOX.x + LEFT_SUPPLY_OFFSET
    figure.supply(f'M{supply_x},{RASPBERRY_PI_BOX.bottom} V{MCU_BOX.y - HEAD_TIP}', Source.BANK)
    figure.wire(f'M{supply_x + PAIR_GAP},{RASPBERRY_PI_BOX.bottom} V{MCU_BOX.y}', LineKind.DATA)
    figure.text(supply_x + PAIR_GAP + 9, baseline_between(RASPBERRY_PI_BOX.bottom, MCU_BOX.y),
                f'{USB_VOLTAGE} and data, USB', 'volt-bank')
    figure.labeled_box(MCU_BOX, 'part', [TextLine('Microcontroller (MCU)', 'name'),
                                         TextLine('Teensy 4.0', 'note')])


def draw_driver_logic_lines(figure: Figure) -> None:
    """Add the motor driver's logic lines from the MCU: 3.3 V, I2C and ground.

    They run to the motor driver's box, which stands beside the MCU's box in the right column.
    """
    left_edge, right_edge = MCU_BOX.right, RIGHT_X
    middle = (left_edge + right_edge) / 2
    supply_y = MCU_BOX.y + 13
    figure.supply(f'M{left_edge},{supply_y} H{right_edge - HEAD_TIP}', Source.BANK)
    figure.text(middle, supply_y - 5, LOGIC_VOLTAGE, 'volt-bank', 'middle')
    i2c_y = supply_y + LOGIC_LINE_GAP
    figure.wire(f'M{left_edge},{i2c_y} H{right_edge}', LineKind.DATA)
    figure.text(middle, i2c_y - 4, 'I2C', 'note', 'middle')
    ground_y = i2c_y + LOGIC_LINE_GAP
    figure.wire(f'M{left_edge},{ground_y} H{right_edge}', LineKind.GROUND)
    figure.text(middle, ground_y - 4, 'GND', 'note', 'middle')


def draw_mcu_sensors(figure: Figure) -> None:
    """Add the MCU's sensors, the encoders and the IMU, each with its supply and data line."""
    for sensor_box, lines in (
            (ENCODERS_BOX, [TextLine('Encoders', 'name'), TextLine('both wheels', 'note')]),
            (IMU_BOX, [TextLine('IMU', 'name'), TextLine('BNO055', 'note')])):
        supply_x = sensor_box.x + 18
        figure.supply(f'M{supply_x},{MCU_BOX.bottom} V{sensor_box.y - HEAD_TIP}', Source.BANK)
        figure.wire(f'M{supply_x + PAIR_GAP},{MCU_BOX.bottom} V{sensor_box.y}', LineKind.DATA)
        figure.text(supply_x + PAIR_GAP + 6, baseline_between(MCU_BOX.bottom, sensor_box.y),
                    LOGIC_VOLTAGE, 'volt-bank')
        figure.labeled_box(sensor_box, 'part', lines)


def remo_power_flow_figure() -> Figure:
    """Return Remo's figure: every part with its checked supply, and the camera's data line."""
    figure = Figure('pf-remo', 400, "Remo's power flow: the power bank supplies the Raspberry Pi, "
                    f'the LiDAR, the Teensy and its sensors, and the {CELL_COUNT} NiMH cells '
                    'supply the motors')
    draw_power_bank_and_pi(figure)
    draw_lidar_and_camera(figure)
    draw_battery_and_motors(figure, [TextLine(BATTERY_NAME, 'name')],
                            f'{BATTERY_VOLTAGE} nominal', [
        TextLine('Motor driver', 'name'), TextLine('Adafruit FeatherWing', 'note'),
        TextLine('joins battery − and GND', 'note')], driver_y=MCU_BOX.y)
    draw_mcu(figure)
    draw_driver_logic_lines(figure)
    draw_mcu_sensors(figure)
    figure.legend(ENCODERS_BOX.bottom + 22,
                  (LEGEND_BANK, LEGEND_BATTERY, LEGEND_DATA, LEGEND_GROUND))
    return figure


def diffbot_power_flow_figure() -> Figure:
    """Return DiffBot's figure: its two supplies, which are the parts that are checked.

    The figure has no legend. Its caption names the two colors.
    """
    figure = Figure('pf-diffbot', 246, "DiffBot's power flow: the power bank supplies the "
                    f'Raspberry Pi, and the {CELL_COUNT} NiMH cells supply the motors')
    draw_power_bank_and_pi(figure)
    draw_battery_and_motors(figure, [TextLine(BATTERY_NAME, 'name')],
                            f'{BATTERY_VOLTAGE} nominal', [
        TextLine('Motor driver', 'name'), TextLine('Grove I2C Motor Driver', 'note'),
        TextLine('makes 5 V for its logic', 'note')], driver_y=96)
    return figure


def write_include(path: str, figure: Figure, caption: str, style: str = '') -> None:
    """Write a figure with its caption to an include, after the style element if one is given.

    The include starts with a comment that names this script.
    """
    with open(path, 'w', encoding='utf-8') as include:
        include.write(f'{GENERATED_COMMENT}{style}<figure class="pf-figure">\n{figure.svg()}\n'
                      f'<figcaption>{caption}</figcaption>\n</figure>\n')


def main() -> None:
    """Write both includes."""
    write_include('includes/power-supply-flow-diffbot.html', diffbot_power_flow_figure(),
                  "DiffBot's two supplies. The blue line is the Raspberry Pi's supply from the "
                  f'power bank. The orange lines are the motor supply from the {CELL_COUNT} NiMH '
                  'cells.',
                  style_element(RULES) + '\n')
    write_include('includes/power-supply-flow-remo.html', remo_power_flow_figure(),
                  "Remo's two supplies. Follow each color from its source at the top. The motor "
                  f'driver is the only part on both supplies. Its logic gets {LOGIC_VOLTAGE} from '
                  'the power bank through the Raspberry Pi and the Teensy. '
                  f'The {CELL_COUNT} cells feed its motor supply, and the driver switches that '
                  'power to the motors.')


if __name__ == '__main__':
    main()
