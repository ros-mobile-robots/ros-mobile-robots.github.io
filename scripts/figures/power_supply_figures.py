def baseline_between(top: float, bottom: float) -> float:
    """Return the baseline of a text line that is centered between the heights top and bottom."""
    return (top + bottom) / 2 + BASELINE_DROP


class Figure(Drawing):
    """Collect the SVG elements of one layout of a figure: its boxes, lines and legend."""

    def __init__(self, name: str, stretch: float, title: str, css_class: str) -> None:
        super().__init__()
        self.name = name  # unique on the page: the ids of its title and arrowheads start with it
        self.stretch = stretch
        self.title = title
        self.css_class = css_class

    def x(self, narrow_x: float) -> float:
        """Return the x position in this layout of an x position of the narrow layout."""
        return narrow_x * self.stretch

    def box_of(self, narrow_box: Box) -> Box:
        """Return a box of the narrow layout in this layout."""
        return Box(self.x(narrow_box.x), narrow_box.y, narrow_box.width * self.stretch,
                   narrow_box.height)

    def part(self, narrow_box: Box, css_class: str, pictogram: Pictogram,
             lines: Sequence[TextLine]) -> Box:
        """Add a part's box with its pictogram at the top and its text lines below, centered.

        Return the box in this layout.
        """
        box = self.box_of(narrow_box)
        self.rect(box.x, box.y, box.width, box.height, css_class, 5)
        scale = min(1.0, PICTOGRAM_HEIGHT / pictogram.height)
        content = (pictogram.height * scale + PICTOGRAM_GAP + CAP_HEIGHT
                   + (len(lines) - 1) * TEXT_LINE_GAP)
        top = box.y + (box.height - content) / 2
        drawing = Drawing()
        pictogram.draw(drawing)
        left = box.x + (box.width - pictogram.width * scale) / 2
        self.elements.append(f'<g transform="translate({left:.1f} {top:.1f}) scale({scale:.3f})">'
                             + ''.join(drawing.elements) + '</g>')
        first = top + pictogram.height * scale + PICTOGRAM_GAP + CAP_HEIGHT
        for index, line in enumerate(lines):
            self.text(box.x + box.width / 2, first + index * TEXT_LINE_GAP, line.text,
                      line.css_class, 'middle')
        return box

    def wire(self, path: str, kind: LineKind) -> None:
        """Add a line of the given kind along an SVG path, without an arrowhead."""
        self.line(path, f'line {kind.value}')

    def supply(self, path: str, source: Source) -> None:
        """Add a supply line with an arrowhead toward the part it feeds.

        The arrowhead's tip is HEAD_TIP units beyond the path's end.
        """
        self.elements.append(f'<path class="line {source.value}" d="{path}" '
                             f'marker-end="url(#{self.name}-{source.value}-head)"/>')

    def legend(self, y: float, entries: Sequence[LegendEntry]) -> None:
        """Add the legend's rows below y: a sample of each line and what it means."""
        left = self.x(POWER_BANK_BOX.x)
        for row, entry in enumerate(entries):
            baseline = y + LEGEND_ROW_GAP * row
            self.wire(f'M{left},{baseline - 3.5} H{left + 26}', entry.kind)
            self.text(left + 34, baseline, entry.meaning)

    def svg(self) -> str:
        """Return the figure as an SVG element."""
        # Each source's supply lines end in an arrowhead of the source's color
        heads = [f'<marker id="{self.name}-{source.value}-head" viewBox="0 0 10 10" '
                 f'refX="{10 - HEAD_TIP}" refY="5" markerUnits="userSpaceOnUse" markerWidth="10" '
                 f'markerHeight="10" orient="auto"><path class="head-{source.value}" '
                 'd="M0,0 L10,5 L0,10 z"/></marker>'
                 for source in Source]
        return svg_element(self.name, f'pf-fig {self.css_class}',
                           (NARROW_WIDTH * self.stretch, HEIGHT), self.title, self.elements,
                           markers=heads)


def draw_power_bank_and_pi(figure: Figure) -> None:
    """Add the power bank and the Raspberry Pi on it."""
    bank = figure.part(POWER_BANK_BOX, 'source bank', POWER_BANK,
                       [TextLine('USB power bank', 'name')])
    pi_box = figure.box_of(RASPBERRY_PI_BOX)
    supply_x = bank.x + LEFT_SUPPLY_OFFSET
    figure.supply(f'M{supply_x},{bank.bottom} V{pi_box.y - HEAD_TIP}', Source.BANK)
    figure.text(supply_x + LABEL_GAP, baseline_between(bank.bottom, pi_box.y),
                f'{USB_VOLTAGE}, USB-C', 'volt-bank')
    figure.part(RASPBERRY_PI_BOX, 'part', RASPBERRY_PI, [TextLine('Raspberry Pi 4 B', 'name')])


class MotorPack(NamedTuple):
    """A robot's motor battery: its label in the figure and captions, and its nominal voltage."""

    label: str
    voltage: str


def legend_entries(pack: MotorPack) -> List[LegendEntry]:
    """Return the legend's entries, with the motor battery's voltage."""
    return [
        LegendEntry(LineKind.BANK_SUPPLY,
                    f'supply from the power bank ({USB_VOLTAGE}, {LOGIC_VOLTAGE})'),
        LegendEntry(LineKind.BATTERY_SUPPLY, f'supply from the motor battery ({pack.voltage})'),
        LegendEntry(LineKind.DATA, 'data connection'),
        LegendEntry(LineKind.GROUND, 'ground wire (GND)'),
    ]


def draw_lidar_and_camera(figure: Figure, camera_name: str) -> None:
    """Add the LiDAR and the camera on the Raspberry Pi.

    The LiDAR's USB adapter gets the supply and the data over one USB cable, the camera over its
    ribbon cable on the Raspberry Pi's camera connector.
    """
    pi_edge = figure.box_of(RASPBERRY_PI_BOX).right
    for narrow_box, voltage, pictogram, lines in (
            (LIDAR_BOX, USB_VOLTAGE, LIDAR,
             [TextLine('RPLidar A2 M8', 'name'), TextLine('USB adapter', 'note')]),
            (CAMERA_BOX, LOGIC_VOLTAGE, CAMERA,
             [TextLine(camera_name, 'name'), TextLine('camera connector', 'note')])):
        box = figure.box_of(narrow_box)
        supply_y = box.y + box.height / 2 - PAIR_GAP / 2
        figure.supply(f'M{pi_edge},{supply_y} H{box.x - HEAD_TIP}', Source.BANK)
        figure.wire(f'M{pi_edge},{supply_y + PAIR_GAP} H{box.x}', LineKind.DATA)
        figure.text((pi_edge + box.x) / 2, supply_y - 5, voltage, 'volt-bank', 'middle')
        figure.part(narrow_box, 'part', pictogram, lines)


def draw_mcu(figure: Figure, mcu_note: str) -> None:
    """Add the microcontroller (MCU), a Teensy on a USB port of the Raspberry Pi.

    One USB cable carries the MCU's supply and its data. mcu_note names the MCU's board.
    """
    pi_box = figure.box_of(RASPBERRY_PI_BOX)
    mcu = figure.box_of(MCU_BOX)
    supply_x = pi_box.x + LEFT_SUPPLY_OFFSET
    figure.supply(f'M{supply_x},{pi_box.bottom} V{mcu.y - HEAD_TIP}', Source.BANK)
    figure.wire(f'M{supply_x + PAIR_GAP},{pi_box.bottom} V{mcu.y}', LineKind.DATA)
    figure.text(supply_x + PAIR_GAP + LABEL_GAP, baseline_between(pi_box.bottom, mcu.y),
                f'{USB_VOLTAGE}, USB', 'volt-bank')
    figure.part(MCU_BOX, 'part', TEENSY,
                [TextLine('Microcontroller (MCU)', 'name'), TextLine(mcu_note, 'note')])


def draw_sensor_on_mcu(figure: Figure, narrow_box: Box, pictogram: Pictogram,
                       lines: Sequence[TextLine]) -> None:
    """Add a sensor below the MCU, with its 3.3 V supply from the MCU and its data line."""
    mcu = figure.box_of(MCU_BOX)
    box = figure.box_of(narrow_box)
    sensor_x = box.x + 18
    figure.supply(f'M{sensor_x},{mcu.bottom} V{box.y - HEAD_TIP}', Source.BANK)
    figure.wire(f'M{sensor_x + PAIR_GAP},{mcu.bottom} V{box.y}', LineKind.DATA)
    figure.text(sensor_x + PAIR_GAP + 6, baseline_between(mcu.bottom, box.y), LOGIC_VOLTAGE,
                'volt-bank')
    figure.part(narrow_box, 'part', pictogram, lines)


ENCODER_LINES = [TextLine('Encoders', 'name'), TextLine('both wheels', 'note')]
