class Source(Enum):
    """The source of a supply. The value is the CSS class of the source's color."""

    BANK = 'bank'
    BATTERY = 'battery'


class LineKind(Enum):
    """What a line of a figure shows. The value is the line's CSS class."""

    BANK_SUPPLY = Source.BANK.value
    BATTERY_SUPPLY = Source.BATTERY.value
    DATA = 'data'
    GROUND = 'ground'


class LegendEntry(NamedTuple):
    """A legend entry: the kind of its line sample and what such a line means."""

    kind: LineKind
    meaning: str


class TextLine(NamedTuple):
    """A line of text in a box: the text and its CSS class."""

    text: str
    css_class: str


class Box(NamedTuple):
    """A box on a figure, in drawing units: its top left corner, its width and its height."""

    x: float
    y: float
    width: float
    height: float

    @property
    def right(self) -> float:
        """Return the x coordinate of the box's right edge."""
        return self.x + self.width

    @property
    def bottom(self) -> float:
        """Return the y coordinate of the box's lower edge."""
        return self.y + self.height


class WireRoute(NamedTuple):
    """A wire's route on the narrow layout: where it leaves a box, its lane and its arrival."""

    leave_y: float
    lane_x: float
    arrive_y: float


class RailRoute(NamedTuple):
    """A supply's route from a box's lower edge: its turn, its lane and its last turn."""

    leave_x: float
    turn_y: float
    lane_x: float
    approach_y: float


class Pictogram(NamedTuple):
    """A drawing of a part: how to draw it with its top left at (0, 0), and its size."""

    draw: Callable[[Drawing], None]
    width: float
    height: float


