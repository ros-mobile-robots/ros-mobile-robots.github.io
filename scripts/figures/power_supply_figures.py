def power_flow_figure(robot: Robot, stretch: float, css_class: str) -> Figure:
    """Return one layout of a robot's figure."""
    figure = Figure(f'pf-{robot.name}-{css_class}', stretch, robot.title, css_class)
    draw_power_bank_and_pi(figure)
    draw_lidar_and_camera(figure, robot.camera_name)
    draw_battery_and_motors(figure, robot.pack, robot.driver_pictogram, robot.driver_lines)
    draw_mcu(figure, robot.mcu_note)
    robot.draw_sensors(figure)
    robot.draw_logic(figure)
    figure.legend(LEGEND_Y, legend_entries(robot.pack))
    return figure


def layouts(robot: Robot) -> List[Figure]:
    """Return the narrow and the wide layout of a robot's figure."""
    return [power_flow_figure(robot, 1, NARROW), power_flow_figure(robot, WIDE_STRETCH, WIDE)]


def write_include(path: str, robot: Robot, caption: str, style: str = '') -> None:
    """Write a robot's figure in both layouts with its caption, after the style if one is given.

    The include starts with a comment that names this script.
    """
    drawings = '\n'.join(figure.svg() for figure in layouts(robot))
    with open(path, 'w', encoding='utf-8') as include:
        include.write(f'{GENERATED_COMMENT}{style}<div class="{SPACE}">\n'
                      f'<figure class="pf-figure">\n{drawings}\n'
                      f'<figcaption>{caption}</figcaption>\n</figure>\n</div>\n')


def main() -> None:
    """Write both includes."""
    write_include('includes/power-supply-flow-diffbot.html', DIFFBOT,
                  f"DiffBot's two supplies. {DIFFBOT.pack.label} feed the Grove driver and the "
                  'motors. The Raspberry Pi sends the motor commands through the Grove I2C hub. '
                  f"The Raspberry Pi's {USB_VOLTAGE} header rail powers both wheel encoders and "
                  "reaches the Grove connector's VCC pin through the hub. The encoders send "
                  'their signals to the Teensy.',
                  style_element(RULES) + '\n')
    write_include('includes/power-supply-flow-remo.html', REMO,
                  "Remo's two supplies. Follow each color from its source at the top. The motor "
                  f'driver is the only part on both supplies. Its logic gets {LOGIC_VOLTAGE} from '
                  'the power bank through the Raspberry Pi and the Teensy. '
                  f'{REMO.pack.label} feed its motor supply, and the driver switches that '
                  'power to the motors.')


if __name__ == '__main__':
    main()
