def draw_sensors_on_mcu_and_pi(figure: Figure) -> None:
    """Add DiffBot's IMU on the MCU's 3.3 V, and its encoders on the Raspberry Pi's 5 V.

    The encoders' data goes to the MCU. Their supply comes from the Raspberry Pi through the
    breadboard's power rail, and runs down the gap between the columns.
    """
    draw_sensor_on_mcu(figure, LEFT_SENSOR_BOX, IMU, IMU_LINES)
    mcu = figure.box_of(MCU_BOX)
    box = figure.box_of(RIGHT_SENSOR_BOX)
    figure.wire(f'M{box.x + 18},{mcu.bottom} V{box.y}', LineKind.DATA)
    rail = DIFFBOT_ENCODER_RAIL
    supply_x = box.x + figure.x(DIFFBOT_ENCODER_SUPPLY_OFFSET)
    lane = figure.x(rail.lane_x)
    figure.supply(f'M{figure.x(rail.leave_x)},{figure.box_of(RASPBERRY_PI_BOX).bottom} '
                  f'V{rail.turn_y} H{lane} V{rail.approach_y} H{supply_x} V{box.y - HEAD_TIP}',
                  Source.BANK)
    figure.text((supply_x + lane) / 2, rail.approach_y - 5, USB_VOLTAGE, 'volt-bank', 'middle')
    figure.part(RIGHT_SENSOR_BOX, 'part', ENCODER, ENCODER_LINES)


def draw_battery_and_motors(figure: Figure, pack: MotorPack, pictogram: Pictogram,
                            driver: Sequence[TextLine]) -> None:
    """Add the motor battery, the motor driver on it and the motors.

    pictogram and driver are the motor driver's drawing and the lines of text in its box.
    """
    battery = figure.part(BATTERY_BOX, 'source battery', BATTERY_HOLDER,
                          [TextLine(pack.label, 'name')])
    driver_box = figure.box_of(DRIVER_BOX)
    motors = figure.box_of(MOTORS_BOX)
    line_x = battery.right - BATTERY_LINE_INSET
    figure.supply(f'M{line_x},{battery.bottom} V{driver_box.y - HEAD_TIP}', Source.BATTERY)
    figure.text(line_x - 8, driver_box.y - 8, f'{pack.voltage} nominal', 'volt-battery', 'end')
    figure.part(DRIVER_BOX, 'part', pictogram, driver)
    motor_x = driver_box.x + driver_box.width / 2
    figure.supply(f'M{motor_x},{driver_box.bottom} V{motors.y - HEAD_TIP}', Source.BATTERY)
    label_y = baseline_between(driver_box.bottom, motors.y)
    figure.text(motor_x - 8, label_y - TEXT_LINE_GAP / 2, 'switched on and off', 'volt-battery',
                'end')
    figure.text(motor_x - 8, label_y + TEXT_LINE_GAP / 2, 'by the driver (PWM)', 'volt-battery',
                'end')
    figure.part(MOTORS_BOX, 'part', GEAR_MOTOR, [TextLine('Two DG01D-E motors', 'name')])


def draw_logic_from_mcu(figure: Figure) -> None:
    """Add Remo's motor driver's logic lines from the MCU: 3.3 V, I2C and ground."""
    left_edge = figure.box_of(MCU_BOX).right
    right_edge = figure.box_of(DRIVER_BOX).x
    middle = (left_edge + right_edge) / 2
    supply_y = MCU_BOX.y + 16
    figure.supply(f'M{left_edge},{supply_y} H{right_edge - HEAD_TIP}', Source.BANK)
    figure.text(middle, supply_y - 5, LOGIC_VOLTAGE, 'volt-bank', 'middle')
    i2c_y = supply_y + LOGIC_LINE_GAP
    figure.wire(f'M{left_edge},{i2c_y} H{right_edge}', LineKind.DATA)
    figure.text(middle, i2c_y - 4, 'I2C', 'note', 'middle')
    ground_y = i2c_y + LOGIC_LINE_GAP
    figure.wire(f'M{left_edge},{ground_y} H{right_edge}', LineKind.GROUND)
    figure.text(middle, ground_y - 4, 'GND', 'note', 'middle')


def draw_i2c_from_pi(figure: Figure) -> None:
    """Add DiffBot's I2C and ground wires from the Raspberry Pi to the motor driver.

    They leave the Raspberry Pi's right edge below the camera's cable, run down the gap between
    the columns through the Grove I2C hub and reach the motor driver beside the MCU.
    """
    pi_edge = figure.box_of(RASPBERRY_PI_BOX).right
    driver_x = figure.box_of(DRIVER_BOX).x
    for route, kind, label in ((DIFFBOT_I2C, LineKind.DATA, 'I2C'),
                               (DIFFBOT_GROUND, LineKind.GROUND, 'GND')):
        lane = figure.x(route.lane_x)
        figure.wire(f'M{pi_edge},{route.leave_y} H{lane} V{route.arrive_y} H{driver_x}', kind)
        figure.text((lane + driver_x) / 2, route.arrive_y - 4, label, 'note', 'middle')
    hub = figure.box_of(DIFFBOT_HUB_BOX)
    figure.rect(hub.x, hub.y, hub.width, hub.height, 'part', 3)
    figure.text(hub.x + hub.width / 2, baseline_between(hub.y, hub.bottom), 'hub', 'note',
                'middle')


class Robot(NamedTuple):
    """What differs between the two robots' figures."""

    name: str  # the robot's name, also the include's name
    title: str  # the drawing's accessible name
    pack: MotorPack
    camera_name: str
    mcu_note: str
    driver_pictogram: Pictogram
    driver_lines: Sequence[TextLine]
    draw_sensors: Callable[[Figure], None]  # the encoders and the IMU with their supplies
    draw_logic: Callable[[Figure], None]  # the motor driver's logic connection


