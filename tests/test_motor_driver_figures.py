from typing import Set
import unittest
from xml.etree import ElementTree

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / 'scripts' / 'figures'))
sys.path.insert(0, str(ROOT / 'tests'))

from figure_script_runs import run_with_an_ascii_locale  # noqa: E402
import motor_driver_figures as figures  # noqa: E402

SCRIPT_NAME = 'motor_driver_figures.py'
PAGE = ROOT / 'docs' / 'theory' / 'actuation.md'
POWER_SUPPLY_PAGE = ROOT / 'docs' / 'power-supply.md'
# The includes that the script has to write, each with the accessible name of its two layouts.
# The names stand here on their own, so that a script that renames one fails a test
DRAWING_TITLES = {'actuation-h-bridge.html': 'Current paths in four H-bridge modes',
                  'actuation-pwm.html': 'Motor voltage at three PWM duty cycles'}
GENERATED_COMMENT = ('<!-- Generated by scripts/figures/motor_driver_figures.py. '
                     'Change the script and run it. -->\n')
# The switches that are on in each mode, from Table 1 of Microchip's application note AN905
AN905_TABLE_1 = {'Forward': {'Q1', 'Q4'}, 'Reverse': {'Q2', 'Q3'}, 'Coast': set(),
                 'Brake': {'Q2', 'Q4'}}
MODES_WITH_A_HIGHLIGHTED_PATH = ['Forward', 'Reverse', 'Brake']
MODES_WITH_AN_ARROWHEAD = ['Forward', 'Reverse']
# The two currents with one direction: the side where each enters the motor and where it leaves
DRIVE_CURRENTS = ((figures.Current.LEFT_TO_RIGHT, figures.Side.LEFT, figures.Side.RIGHT),
                  (figures.Current.RIGHT_TO_LEFT, figures.Side.RIGHT, figures.Side.LEFT))
# A row of the page's table of the modes: the mode and the switches that are closed
MODE_ROW = re.compile(r'^\| (?P<mode>Forward|Reverse|Coast|Brake) \| (?P<closed>[^|]+) \|',
                      re.MULTILINE)
# The row of the Power Supply page's table of Remo's cells with the nominal voltages
NOMINAL_ROW = re.compile(r'^\| Nominal \| (?P<cell>[\d.]+) V \| (?P<pack>[\d.]+) V \|$',
                         re.MULTILINE)
# What the firmware and Adafruit's library 1.1.4 give, calculated by hand from their code
HIGHEST_COMMAND = 255
COUNTS_OF_THE_HIGHEST_COMMAND = 4080
LIBRARY_FREQUENCY_HZ = 1440
PRESCALER_BEFORE_ROUNDING = 3.2386
# The smallest prescaler of the PCA9685 and its highest PWM frequency with the 25 MHz clock, from
# section 7.3.5 of its datasheet
SMALLEST_PRESCALER = 3
HIGHEST_FREQUENCY_HZ = 1526
PERIOD_AT_THE_HIGHEST_FREQUENCY_MS = 0.65536
# The drawings write their coordinates with up to six digits
COORDINATE_PLACES = 3


class Segment(NamedTuple):
    """A straight piece of a drawn line, from (x1, y1) to (x2, y2)."""

    x1: float
    y1: float
    x2: float
    y2: float


def path_segments(path: str) -> List[Segment]:
    """Return the straight pieces of an SVG path made of absolute M, L, H, V and Z commands."""
    segments: List[Segment] = []
    x = y = start_x = start_y = 0.0
    for command, numbers in re.findall(r'([MLHVZ])([^MLHVZ]*)', path):
        values = [float(value) for value in re.split(r'[ ,]+', numbers.strip()) if value]
        if command == 'M':
            x, y = start_x, start_y = values[0], values[1]
            continue
        if command == 'H':
            new_x, new_y = values[0], y
        elif command == 'V':
            new_x, new_y = x, values[0]
        elif command == 'L':
            new_x, new_y = values[0], values[1]
        else:
            new_x, new_y = start_x, start_y
        segments.append(Segment(x, y, new_x, new_y))
        x, y = new_x, new_y
    return segments


def include_drawings(include_name: str) -> List[ElementTree.Element]:
    """Return the SVG elements of a committed include, in their order."""
    include = (ROOT / 'includes' / include_name).read_text(encoding='utf-8')
    return [ElementTree.fromstring(drawing)
            for drawing in re.findall(r'<svg .*?</svg>', include, re.DOTALL)]


def paths_of_class(drawing: ElementTree.Element, css_class: str) -> List[str]:
    """Return the path data of a drawing's paths whose class is exactly css_class."""
    return [path.get('d', '') for path in drawing.iter('path')
            if path.get('class') == css_class]


def drawn_texts(drawing: ElementTree.Element) -> List[str]:
    """Return the texts of a drawing's text elements, each with the text of its spans."""
    return [''.join(text.itertext()) for text in drawing.iter('text')]


def switches_on_a_path(panel: figures.Panel, path: str) -> Set[str]:
    """Return the names of the switches that a path runs through from contact to contact."""
    on_the_path = set()
    for switch in figures.SWITCHES:
        switch_x = panel.half_bridge_x(switch.side)
        upper_y = panel.switch_y(switch)
        lower_y = upper_y + figures.SWITCH_LENGTH
        for segment in path_segments(path):
            if (segment.x1 == segment.x2 == switch_x
                    and min(segment.y1, segment.y2) <= upper_y
                    and max(segment.y1, segment.y2) >= lower_y):
                on_the_path.add(switch.name)
    return on_the_path


def passes_the_motor(panel: figures.Panel, path: str) -> bool:
    """Return whether a path runs through the motor from one side to the other."""
    return any(segment.y1 == segment.y2 == panel.motor_y
               and min(segment.x1, segment.x2) < panel.motor_x - figures.MOTOR_RADIUS
               and max(segment.x1, segment.x2) > panel.motor_x + figures.MOTOR_RADIUS
               for segment in path_segments(path))


class TestIncludes(unittest.TestCase):
    """The script writes the repository's includes, each with its comment, styles and layouts.

    The includes have characters outside ASCII, the sign for about among them.
    """

    def test_script_writes_the_repository_includes_with_an_ascii_locale(self) -> None:
        written = run_with_an_ascii_locale(SCRIPT_NAME)
        self.assertEqual(sorted(written), sorted(DRAWING_TITLES))
        for include_name in DRAWING_TITLES:
            committed = (ROOT / 'includes' / include_name).read_bytes()
            self.assertEqual(written[include_name], committed,
                             f'{include_name} is not what {SCRIPT_NAME} writes')

    def test_each_include_starts_with_the_comment_that_names_the_script(self) -> None:
        for include in (figures.h_bridge_include(), figures.pwm_include()):
            self.assertTrue(include.startswith(GENERATED_COMMENT), include[:120])

    def test_each_include_holds_one_narrow_and_one_wide_layout(self) -> None:
        for include_name in DRAWING_TITLES:
            classes = [drawing.get('class') for drawing in include_drawings(include_name)]
            self.assertEqual(classes, ['ac-fig ac-narrow', 'ac-fig ac-wide'], include_name)

    def test_every_layout_is_an_image_named_by_its_own_title(self) -> None:
        title_ids = []
        for include_name, expected_title in DRAWING_TITLES.items():
            for drawing in include_drawings(include_name):
                title = drawing.find('title')
                assert title is not None, include_name
                self.assertEqual(drawing.get('role'), 'img', include_name)
                self.assertEqual(drawing.get('aria-labelledby'), title.get('id'), include_name)
                self.assertEqual(title.text, expected_title, include_name)
                title_ids.append(title.get('id'))
        # Both includes stand on one page, so no two of their drawings may share an ID
        self.assertEqual(len(set(title_ids)), len(title_ids), title_ids)

    def test_every_class_that_a_layout_draws_has_a_rule_in_its_includes_style(self) -> None:
        for include_name, rules in (('actuation-h-bridge.html', figures.BRIDGE_RULES),
                                    ('actuation-pwm.html', figures.PWM_RULES)):
            # The layouts' classes appear in the selectors inside the container query's rule
            styled = set()
            for selector, declarations in rules:
                styled.update(re.findall(r'\.([A-Za-z][\w-]*)', f'{selector} {declarations}'))
            for drawing in include_drawings(include_name):
                for element in drawing.iter():
                    for css_class in element.get('class', '').split():
                        self.assertIn(css_class, styled, (include_name, css_class))

    def test_no_text_has_the_accent_color(self) -> None:
        # The accent color on the page's light background has too little contrast for small text
        text_classes = set()
        for include_name in DRAWING_TITLES:
            for drawing in include_drawings(include_name):
                for element in drawing.iter():
                    if element.tag in ('text', 'tspan'):
                        text_classes.update(element.get('class', '').split())
        self.assertIn('average-label', text_classes)
        for selector, declarations in figures.BRIDGE_RULES + figures.PWM_RULES:
            styles_text = selector.endswith(' text') or any(
                selector.endswith(f'.{css_class}') for css_class in text_classes)
            if styles_text:
                self.assertNotIn('--ac-current', declarations, selector)


class TestModes(unittest.TestCase):
    """The modes close the switches of AN905's Table 1, and the drawn current follows them."""

    def test_the_modes_close_the_switches_of_an905s_table_1(self) -> None:
        closed_by_mode = {mode.name: set(mode.closed) for mode in figures.MODES}
        self.assertEqual(closed_by_mode, AN905_TABLE_1)

    def test_no_mode_closes_both_switches_of_a_half_bridge(self) -> None:
        for mode in figures.MODES:
            for side in figures.Side:
                on_the_side = {switch.name for switch in figures.SWITCHES if switch.side is side}
                self.assertLess(len(on_the_side & mode.closed), 2, (mode.name, side))

    def test_each_modes_current_follows_from_its_closed_switches(self) -> None:
        currents = {mode.name: figures.current_of(mode) for mode in figures.MODES}
        self.assertEqual(currents, {'Forward': figures.Current.LEFT_TO_RIGHT,
                                    'Reverse': figures.Current.RIGHT_TO_LEFT,
                                    'Coast': figures.Current.NONE,
                                    'Brake': figures.Current.GROUND_LOOP})

    def test_two_closed_supply_switches_give_a_loop_through_the_supply_rail(self) -> None:
        high_side_brake = figures.Mode('High-side brake', frozenset({'Q1', 'Q3'}))
        current = figures.current_of(high_side_brake)
        self.assertIs(current, figures.Current.SUPPLY_LOOP)
        panel = figures.BRIDGE_LAYOUTS[0].panel(0)
        path = figures.current_path(panel, current)
        self.assertEqual(switches_on_a_path(panel, path), set(high_side_brake.closed))
        self.assertTrue(passes_the_motor(panel, path))

    def test_a_mode_with_a_floating_terminal_has_no_current(self) -> None:
        for closed in ('Q1', 'Q2', 'Q3', 'Q4'):
            one_switch_closed = figures.Mode(f'Only {closed}', frozenset({closed}))
            self.assertIs(figures.current_of(one_switch_closed), figures.Current.NONE, closed)

    def test_the_highlighted_path_passes_the_motor_and_exactly_the_closed_switches(self) -> None:
        for layout in figures.BRIDGE_LAYOUTS:
            for index, mode in enumerate(figures.MODES):
                if mode.name not in MODES_WITH_A_HIGHLIGHTED_PATH:
                    continue
                panel = layout.panel(index)
                path = figures.current_path(panel, figures.current_of(mode))
                self.assertEqual(switches_on_a_path(panel, path), set(mode.closed),
                                 (layout.css_class, mode.name))
                self.assertTrue(passes_the_motor(panel, path), (layout.css_class, mode.name))

    def test_a_drive_current_runs_from_the_supply_rail_to_the_ground_rail(self) -> None:
        panel = figures.BRIDGE_LAYOUTS[0].panel(0)
        for current, enters, leaves in DRIVE_CURRENTS:
            segments = path_segments(figures.current_path(panel, current))
            self.assertEqual((segments[0].x1, segments[0].y1),
                             (panel.half_bridge_x(enters), panel.rail_y(figures.Rail.SUPPLY)))
            self.assertEqual((segments[-1].x2, segments[-1].y2),
                             (panel.half_bridge_x(leaves), panel.rail_y(figures.Rail.GROUND)))

    def test_the_arrowhead_points_the_way_the_current_passes_the_motor(self) -> None:
        panel = figures.BRIDGE_LAYOUTS[0].panel(0)
        for current, _, leaves in DRIVE_CURRENTS:
            # The path starts at one end of the arrowhead's base and runs to its tip first
            base_to_tip = path_segments(figures.arrowhead_path(panel, current))[0]
            toward_the_leaving_side = panel.half_bridge_x(leaves) - panel.motor_x
            self.assertGreater((base_to_tip.x2 - base_to_tip.x1) * toward_the_leaving_side, 0,
                               current)
            # The arrowhead stands on the side of the motor where the current leaves it
            self.assertGreater((base_to_tip.x2 - panel.motor_x) * toward_the_leaving_side, 0,
                               current)

    def test_each_layout_highlights_three_modes_paths_and_gives_two_an_arrowhead(self) -> None:
        for layout in figures.BRIDGE_LAYOUTS:
            drawing = ElementTree.fromstring(figures.h_bridge_figure(layout))
            expected_paths = [
                figures.current_path(layout.panel(index), figures.current_of(mode))
                for index, mode in enumerate(figures.MODES)
                if mode.name in MODES_WITH_A_HIGHLIGHTED_PATH]
            self.assertEqual(paths_of_class(drawing, 'current'), expected_paths,
                             layout.css_class)
            self.assertEqual(len(paths_of_class(drawing, 'current-head')),
                             len(MODES_WITH_AN_ARROWHEAD), layout.css_class)

    def test_each_panel_names_its_mode_and_its_closed_switches(self) -> None:
        for layout in figures.BRIDGE_LAYOUTS:
            texts = drawn_texts(ElementTree.fromstring(figures.h_bridge_figure(layout)))
            for expected in ('Forward', 'Q1 and Q4 closed', 'Reverse', 'Q2 and Q3 closed',
                             'Coast', 'all open', 'Brake', 'Q2 and Q4 closed'):
                self.assertEqual(texts.count(expected), 1, (layout.css_class, expected))

    def test_the_pages_table_closes_the_same_switches_as_the_figure(self) -> None:
        rows = {row['mode']: row['closed'].strip()
                for row in MODE_ROW.finditer(PAGE.read_text(encoding='utf-8'))}
        self.assertEqual(sorted(rows), sorted(mode.name for mode in figures.MODES))
        for mode in figures.MODES:
            named = set(re.findall(r'Q\d', rows[mode.name]))
            self.assertEqual(named, set(mode.closed), mode.name)


class TestPwm(unittest.TestCase):
    """The duty cycles, averages and frequency follow Adafruit's library and the PCA9685."""

    def test_the_figures_commands_give_quarter_duty_cycles(self) -> None:
        self.assertEqual([pulse.counts for pulse in figures.pulses()], [1024, 2048, 3072])
        self.assertEqual([pulse.duty for pulse in figures.pulses()], [0.25, 0.5, 0.75])

    def test_the_highest_command_is_on_for_4080_of_4096_counts(self) -> None:
        self.assertEqual(figures.MAX_COMMAND, HIGHEST_COMMAND)
        self.assertEqual(figures.pulse_of(figures.MAX_COMMAND).counts,
                         COUNTS_OF_THE_HIGHEST_COMMAND)

    def test_a_reverse_command_has_the_duty_cycle_of_its_magnitude(self) -> None:
        forward_command = 128
        self.assertEqual(figures.pulse_of(-forward_command).duty,
                         figures.pulse_of(forward_command).duty)

    def test_each_average_is_the_duty_cycle_times_the_supply(self) -> None:
        for pulse in figures.pulses():
            self.assertAlmostEqual(pulse.average, pulse.duty * figures.SUPPLY_VOLTAGE)
        self.assertEqual([figures.volts(pulse.average) for pulse in figures.pulses()],
                         ['2.4 V', '4.8 V', '7.2 V'])

    def test_the_supply_is_the_nominal_voltage_of_remos_pack_on_the_power_supply_page(
            self) -> None:
        row = NOMINAL_ROW.search(POWER_SUPPLY_PAGE.read_text(encoding='utf-8'))
        assert row is not None, 'the Power Supply page has no row of nominal voltages'
        self.assertAlmostEqual(figures.NIMH_NOMINAL_CELL_VOLTAGE, float(row['cell']))
        self.assertAlmostEqual(figures.SUPPLY_VOLTAGE, float(row['pack']))

    def test_the_library_calculates_the_prescaler_for_nine_tenths_of_the_request(self) -> None:
        self.assertAlmostEqual(figures.library_frequency_hz(), LIBRARY_FREQUENCY_HZ)
        self.assertAlmostEqual(figures.prescaler_before_rounding(), PRESCALER_BEFORE_ROUNDING,
                               places=4)

    def test_the_rounded_prescaler_is_the_chips_smallest_and_gives_its_highest_frequency(
            self) -> None:
        self.assertEqual(figures.prescaler(), SMALLEST_PRESCALER)
        self.assertEqual(round(figures.frequency_hz()), HIGHEST_FREQUENCY_HZ)
        self.assertAlmostEqual(figures.period_ms(), PERIOD_AT_THE_HIGHEST_FREQUENCY_MS)

    def test_each_rows_voltage_is_high_for_its_duty_cycle_share_of_every_period(self) -> None:
        row_top = 0.0
        for layout in figures.PWM_LAYOUTS:
            for pulse in figures.pulses():
                high_pieces = [segment for segment in path_segments(
                    figures.wave_path(layout, row_top, pulse.duty))
                    if segment.y1 == segment.y2 == row_top]
                self.assertEqual(len(high_pieces), figures.PERIODS, layout.css_class)
                for index, piece in enumerate(high_pieces):
                    self.assertAlmostEqual(piece.x1,
                                           figures.PLOT_LEFT + index * layout.period_width,
                                           COORDINATE_PLACES)
                    self.assertAlmostEqual((piece.x2 - piece.x1) / layout.period_width,
                                           pulse.duty, COORDINATE_PLACES)

    def test_the_periods_fill_the_plot_and_end_inside_the_drawing(self) -> None:
        for layout in figures.PWM_LAYOUTS:
            segments = path_segments(figures.wave_path(layout, 0.0, 0.5))
            self.assertEqual(segments[0].x1, figures.PLOT_LEFT, layout.css_class)
            self.assertAlmostEqual(segments[-1].x2, layout.plot_right, COORDINATE_PLACES)
            self.assertLess(layout.plot_right, layout.width, layout.css_class)

    def test_each_rows_average_line_lies_at_its_share_of_the_supply_level(self) -> None:
        for layout in figures.PWM_LAYOUTS:
            drawing = ElementTree.fromstring(figures.pwm_figure(layout))
            waves = paths_of_class(drawing, 'wave')
            averages = paths_of_class(drawing, 'average')
            self.assertEqual(len(averages), len(figures.COMMANDS), layout.css_class)
            for wave, average, pulse in zip(waves, averages, figures.pulses()):
                levels = [segment.y1 for segment in path_segments(wave)
                          if segment.y1 == segment.y2]
                zero_level, supply_level = max(levels), min(levels)
                average_level = path_segments(average)[0].y1
                self.assertAlmostEqual(
                    (zero_level - average_level) / (zero_level - supply_level), pulse.duty,
                    COORDINATE_PLACES, (layout.css_class, pulse.command))

    def test_each_layout_labels_the_two_voltage_levels_and_the_period(self) -> None:
        for layout in figures.PWM_LAYOUTS:
            texts = drawn_texts(ElementTree.fromstring(figures.pwm_figure(layout)))
            for expected in ('9.6 V', '0 V', 'One period T ≈ 0.66 ms'):
                self.assertEqual(texts.count(expected), 1, (layout.css_class, expected))

    def test_each_row_is_labelled_with_its_duty_cycle_its_command_and_its_average(self) -> None:
        for layout in figures.PWM_LAYOUTS:
            texts = drawn_texts(ElementTree.fromstring(figures.pwm_figure(layout)))
            for expected in ('25 %', 'command 64', 'average 2.4 V',
                             '50 %', 'command 128', 'average 4.8 V',
                             '75 %', 'command 192', 'average 7.2 V'):
                self.assertEqual(texts.count(expected), 1, (layout.css_class, expected))


class TestPage(unittest.TestCase):
    """The page's text repeats the numbers that the script calculates."""

    def test_the_page_repeats_the_scripts_numbers(self) -> None:
        page = PAGE.read_text(encoding='utf-8')
        half_duty = figures.pulse_of(128)
        self.assertIn(f'The command {half_duty.command}, for example, gives {half_duty.counts} '
                      f'of {figures.COUNTS_PER_PERIOD} counts, a duty cycle of '
                      f'{figures.percent(half_duty.duty)}', page)
        highest = figures.pulse_of(figures.MAX_COMMAND)
        self.assertIn(f'The highest command, {highest.command}, gives {highest.counts} of '
                      f'{figures.COUNTS_PER_PERIOD} counts, a duty cycle of '
                      f'{figures.percent(highest.duty)}', page)
        self.assertIn(f"rounds the chip's prescaler to {figures.prescaler()}", page)
        self.assertIn(f'about {figures.frequency_hz():.0f} Hz', page)
        self.assertIn(f'about {figures.period_ms():.2f} ms', page)


if __name__ == '__main__':
    unittest.main()
