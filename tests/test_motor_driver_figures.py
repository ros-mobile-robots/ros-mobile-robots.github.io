def include_drawings(include_name: str) -> List[ElementTree.Element]:
    """Return the SVG elements of a committed include, in their order."""
    include = (ROOT / 'includes' / include_name).read_text(encoding='utf-8')
    return [ElementTree.fromstring(drawing)
            for drawing in re.findall(r'<svg .*?</svg>', include, re.DOTALL)]


class Circle(NamedTuple):
    """A drawn circle: its center and its radius."""

    x: float
    y: float
    radius: float

    def holds(self, x: float, y: float) -> bool:
        """Return whether the point (x, y) lies in the circle."""
        return math.hypot(x - self.x, y - self.y) <= self.radius


class Label(NamedTuple):
    """A drawn line of text: its anchor point, its text with that of its spans, its class."""

    x: float
    y: float
    text: str
    css_class: str


def only(items: Iterable[Item]) -> Item:
    """Return the one item of items, and raise a ValueError for none or more than one."""
    found = list(items)
    if len(found) != 1:
        raise ValueError(f'expected one item, found {found}')
    return found[0]


def drawn_paths(drawing: ElementTree.Element, css_class: str) -> List[List[Segment]]:
    """Return the straight pieces of each path whose class is exactly css_class, in order."""
    return [path_segments(path.get('d', '')) for path in drawing.iter('path')
            if path.get('class') == css_class]


def drawn_circles(drawing: ElementTree.Element, css_class: str) -> List[Circle]:
    """Return the circles whose class is exactly css_class, in their order."""
    return [Circle(float(circle.get('cx', 0)), float(circle.get('cy', 0)),
                   float(circle.get('r', 0)))
            for circle in drawing.iter('circle') if circle.get('class') == css_class]


def drawn_labels(drawing: ElementTree.Element) -> List[Label]:
    """Return the lines of text of a drawing, in their order."""
    return [Label(float(text.get('x', 0)), float(text.get('y', 0)), ''.join(text.itertext()),
                  text.get('class', ''))
            for text in drawing.iter('text')]


class Lever(NamedTuple):
    """A drawn lever of a switch: its piece, and whether it has the stroke of a closed switch."""

    piece: Segment
    bold: bool


class DrawnBridge(NamedTuple):
    """What one panel of the H-bridge figure shows, read from the drawing's SVG."""

    mode: str  # the panel's title
    labels: List[Label]
    levers: Dict[str, Lever]  # each lever by the switch name on the label beside it
    contacts: List[Circle]
    motor: Circle
    rails: List[Segment]  # from top to bottom
    wires: List[Segment]
    highlighted_paths: List[List[Segment]]
    arrowheads: List[List[Segment]]

    def contacts_of(self, name: str) -> Tuple[Circle, Circle]:
        """Return the two contacts of a switch, the upper one first.

        The lever of a switch starts in its upper contact. Its lower contact is the next
        contact below on the same half-bridge.
        """
        start = self.levers[name].piece
        upper = only(contact for contact in self.contacts if contact.holds(start.x1, start.y1))
        below = [contact for contact in self.contacts
                 if contact.x == upper.x and contact.y > upper.y]
        return upper, min(below, key=lambda contact: contact.y)

    @property
    def closed(self) -> Set[str]:
        """Return the names of the switches whose lever joins both of their contacts."""
        return {name for name, lever in self.levers.items()
                if self.contacts_of(name)[1].holds(lever.piece.x2, lever.piece.y2)}

    @property
    def half_bridge_xs(self) -> List[float]:
        """Return the x of the left and of the right half-bridge."""
        return sorted({contact.x for contact in self.contacts})


def is_inside(panel: figures.Panel, x: float, y: float) -> bool:
    """Return whether the point (x, y) lies in a panel."""
    return (panel.left <= x <= panel.left + panel.width
            and panel.top <= y <= panel.top + figures.PANEL_HEIGHT)


def starts_inside(panel: figures.Panel, pieces: Sequence[Segment]) -> bool:
    """Return whether a drawn path starts in a panel."""
    return is_inside(panel, pieces[0].x1, pieces[0].y1)


def name_beside(lever: Segment, labels: Sequence[Label]) -> str:
    """Return the switch name on the label that is nearest to where a lever starts."""
    names = [label for label in labels if re.fullmatch(r'Q\d', label.text)]
    return min(names, key=lambda label: math.hypot(label.x - lever.x1, label.y - lever.y1)).text


def drawn_levers(drawing: ElementTree.Element, panel: figures.Panel,
                 labels: Sequence[Label]) -> Dict[str, Lever]:
    """Return the levers that a panel shows, each by the switch name beside it."""
    levers = {}
    for css_class, bold in (('switch', False), ('switch closed', True)):
        for pieces in drawn_paths(drawing, css_class):
            if starts_inside(panel, pieces):
                levers[name_beside(pieces[0], labels)] = Lever(only(pieces), bold)
    return levers


def drawn_bridge(drawing: ElementTree.Element, panel: figures.Panel) -> DrawnBridge:
    """Return what one panel of an H-bridge drawing shows."""
    labels = [label for label in drawn_labels(drawing) if is_inside(panel, label.x, label.y)]
    return DrawnBridge(
        mode=only(label.text for label in labels if label.css_class == 'name strong'),
        labels=labels,
        levers=drawn_levers(drawing, panel, labels),
        contacts=[circle for circle in drawn_circles(drawing, 'contact')
                  if is_inside(panel, circle.x, circle.y)],
        motor=only(circle for circle in drawn_circles(drawing, 'motor')
                   if is_inside(panel, circle.x, circle.y)),
        rails=sorted((only(pieces) for pieces in drawn_paths(drawing, 'rail')
                      if starts_inside(panel, pieces)), key=lambda rail: rail.y1),
        wires=[piece for pieces in drawn_paths(drawing, 'wire') for piece in pieces
               if is_inside(panel, piece.x1, piece.y1)],
        highlighted_paths=[pieces for pieces in drawn_paths(drawing, 'current')
                           if starts_inside(panel, pieces)],
        arrowheads=[pieces for pieces in drawn_paths(drawing, 'current-head')
                    if starts_inside(panel, pieces)])


def drawn_bridges(layout: figures.BridgeLayout) -> List[DrawnBridge]:
    """Return what each panel of a layout's generated drawing shows, in the panels' order."""
    drawing = ElementTree.fromstring(figures.h_bridge_figure(layout))
    return [drawn_bridge(drawing, layout.panel(index)) for index in range(len(AN905_TABLE_1))]


def runs_between(path: Sequence[Segment], upper: Circle, lower: Circle) -> bool:
    """Return whether a path runs straight from one contact of a switch to the other."""
    return any(piece.x1 == piece.x2 == upper.x
               and min(piece.y1, piece.y2) <= upper.y and max(piece.y1, piece.y2) >= lower.y
               for piece in path)


def crosses(path: Sequence[Segment], circle: Circle) -> bool:
    """Return whether a path runs level through a circle's center from one side to the other."""
    return any(piece.y1 == piece.y2 == circle.y
               and min(piece.x1, piece.x2) < circle.x - circle.radius
               and max(piece.x1, piece.x2) > circle.x + circle.radius
               for piece in path)


class DrawnRow(NamedTuple):
    """What one row of the PWM figure shows, read from the drawing's SVG."""

    duty_label: Label
    command_label: Label
    average_label: Label
    wave: List[Segment]
    average_line: Segment

    @property
    def supply_level(self) -> float:
        """Return the y of the wave's upper level."""
        return min(piece.y1 for piece in self.wave)

    @property
    def zero_level(self) -> float:
        """Return the y of the wave's lower level."""
        return max(piece.y1 for piece in self.wave)

    @property
    def pulses(self) -> List[Segment]:
        """Return the pieces of the wave at its upper level, from left to right."""
        return [piece for piece in self.wave if piece.y1 == piece.y2 == self.supply_level]

    @property
    def gaps(self) -> List[Segment]:
        """Return the pieces of the wave at its lower level, from left to right."""
        return [piece for piece in self.wave if piece.y1 == piece.y2 == self.zero_level]

    @property
    def start_x(self) -> float:
        """Return the x where the wave starts."""
        return self.wave[0].x1

    @property
    def end_x(self) -> float:
        """Return the x where the wave ends."""
        return self.wave[-1].x2


def drawn_row(wave: List[Segment], labels: Sequence[Label],
              average_lines: Sequence[Segment]) -> DrawnRow:
    """Return a row from its wave, with the texts and the average line at the wave's height."""
    top = min(piece.y1 for piece in wave)
    bottom = max(piece.y1 for piece in wave)
    beside = [label for label in labels if top <= label.y <= bottom + BELOW_WAVE_REACH]
    return DrawnRow(
        duty_label=only(label for label in beside if label.css_class == 'name strong'),
        command_label=only(label for label in beside if label.text.startswith('command ')),
        average_label=only(label for label in beside if label.css_class == 'average-label'),
        wave=wave,
        average_line=only(line for line in average_lines if top <= line.y1 <= bottom))


def drawn_rows(drawing: ElementTree.Element) -> List[DrawnRow]:
    """Return what each row of a PWM drawing shows, from top to bottom."""
    labels = drawn_labels(drawing)
    average_lines = [only(pieces) for pieces in drawn_paths(drawing, 'average')]
    waves = sorted(drawn_paths(drawing, 'wave'), key=lambda wave: wave[0].y1)
    return [drawn_row(wave, labels, average_lines) for wave in waves]


def switches_on_a_path(panel: figures.Panel, path: str) -> Set[str]:
    """Return the names of the switches that a path runs through from contact to contact."""
    on_the_path = set()
    for switch in figures.SWITCHES:
        switch_x = panel.half_bridge_x(switch.side)
        upper_y = panel.switch_y(switch)
        lower_y = upper_y + figures.SWITCH_LENGTH
        for segment in path_segments(path):
            if (segment.x1 == segment.x2 == switch_x
                    and min(segment.y1, segment.y2) <= upper_y
                    and max(segment.y1, segment.y2) >= lower_y):
                on_the_path.add(switch.name)
    return on_the_path


def passes_the_motor(panel: figures.Panel, path: str) -> bool:
    """Return whether a path runs through the motor from one side to the other."""
    return any(segment.y1 == segment.y2 == panel.motor_y
               and min(segment.x1, segment.x2) < panel.motor_x - figures.MOTOR_RADIUS
               and max(segment.x1, segment.x2) > panel.motor_x + figures.MOTOR_RADIUS
               for segment in path_segments(path))


class TestIncludes(unittest.TestCase):
    """The script writes the repository's includes, each with its comment, styles and layouts.

    The includes have characters outside ASCII, the sign for about among them.
    """

    def test_script_writes_the_repository_includes_with_an_ascii_locale(self) -> None:
        written = run_with_an_ascii_locale(SCRIPT_NAME)
        self.assertEqual(sorted(written), sorted(DRAWING_TITLES))
        for include_name in DRAWING_TITLES:
            committed = (ROOT / 'includes' / include_name).read_bytes()
            self.assertEqual(written[include_name], committed,
                             f'{include_name} is not what {SCRIPT_NAME} writes')

    def test_each_include_starts_with_the_comment_that_names_the_script(self) -> None:
        for include in (figures.h_bridge_include(), figures.pwm_include()):
            self.assertTrue(include.startswith(GENERATED_COMMENT), include[:120])

    def test_each_include_holds_one_narrow_and_one_wide_layout(self) -> None:
        for include_name in DRAWING_TITLES:
            classes = [drawing.get('class') for drawing in include_drawings(include_name)]
            self.assertEqual(classes, ['ac-fig ac-narrow', 'ac-fig ac-wide'], include_name)

    def test_every_layout_is_an_image_named_by_its_own_title(self) -> None:
        title_ids = []
        for include_name, expected_title in DRAWING_TITLES.items():
            for drawing in include_drawings(include_name):
                title = drawing.find('title')
                assert title is not None, include_name
                self.assertEqual(drawing.get('role'), 'img', include_name)
                self.assertEqual(drawing.get('aria-labelledby'), title.get('id'), include_name)
                self.assertEqual(title.text, expected_title, include_name)
                title_ids.append(title.get('id'))
        # Both includes stand on one page, so no two of their drawings may share an ID
        self.assertEqual(len(set(title_ids)), len(title_ids), title_ids)

    def test_every_class_that_a_layout_draws_has_a_rule_in_its_includes_style(self) -> None:
        for include_name, rules in (('actuation-h-bridge.html', figures.BRIDGE_RULES),
                                    ('actuation-pwm.html', figures.PWM_RULES)):
            # The layouts' classes appear in the selectors inside the container query's rule
            styled = set()
            for selector, declarations in rules:
                styled.update(re.findall(r'\.([A-Za-z][\w-]*)', f'{selector} {declarations}'))
            for drawing in include_drawings(include_name):
                for element in drawing.iter():
                    for css_class in element.get('class', '').split():
                        self.assertIn(css_class, styled, (include_name, css_class))

    def test_no_text_has_the_accent_color(self) -> None:
        # The accent color on the page's light background has too little contrast for small text
        text_classes = set()
        for include_name in DRAWING_TITLES:
            for drawing in include_drawings(include_name):
                for element in drawing.iter():
                    if element.tag in ('text', 'tspan'):
                        text_classes.update(element.get('class', '').split())
        self.assertIn('average-label', text_classes)
        for selector, declarations in figures.BRIDGE_RULES + figures.PWM_RULES:
            styles_text = selector.endswith(' text') or any(
                selector.endswith(f'.{css_class}') for css_class in text_classes)
            if styles_text:
                self.assertNotIn('--ac-current', declarations, selector)


class TestDrawingBounds(unittest.TestCase):
    """Nothing of a generated drawing lies outside the drawing, where it would be cut off."""

    def test_every_text_circle_and_path_point_lies_inside_its_drawing(self) -> None:
        drawings = ([figures.h_bridge_figure(layout) for layout in figures.BRIDGE_LAYOUTS]
                    + [figures.pwm_figure(layout) for layout in figures.PWM_LAYOUTS])
        for drawing in map(ElementTree.fromstring, drawings):
            width, height = (float(number) for number in drawing.get('viewBox', '').split()[2:])
            points = [(label.x, label.y) for label in drawn_labels(drawing)]
            for circle in drawing.iter('circle'):
                center_x, center_y = float(circle.get('cx', 0)), float(circle.get('cy', 0))
                radius = float(circle.get('r', 0))
                points += [(center_x - radius, center_y - radius),
                           (center_x + radius, center_y + radius)]
            for path in drawing.iter('path'):
                for piece in path_segments(path.get('d', '')):
                    points += [(piece.x1, piece.y1), (piece.x2, piece.y2)]
            for x, y in points:
                self.assertTrue(0 <= x <= width and 0 <= y <= height,
                                (drawing.get('class'), drawing.findtext('title'), x, y))


class TestModes(unittest.TestCase):
    """The modes close the switches of AN905's Table 1, and each mode's current follows them."""

    def test_the_modes_close_the_switches_of_an905s_table_1(self) -> None:
        closed_by_mode = {mode.name: set(mode.closed) for mode in figures.MODES}
        self.assertEqual(closed_by_mode, AN905_TABLE_1)

    def test_no_mode_closes_both_switches_of_a_half_bridge(self) -> None:
        for mode in figures.MODES:
            for side in figures.Side:
                on_the_side = {switch.name for switch in figures.SWITCHES if switch.side is side}
                self.assertLess(len(on_the_side & mode.closed), 2, (mode.name, side))

    def test_each_modes_current_follows_from_its_closed_switches(self) -> None:
        currents = {mode.name: figures.current_of(mode) for mode in figures.MODES}
        self.assertEqual(currents, {'Forward': figures.Current.LEFT_TO_RIGHT,
                                    'Reverse': figures.Current.RIGHT_TO_LEFT,
                                    'Coast': figures.Current.NONE,
                                    'Brake': figures.Current.GROUND_LOOP})

    def test_two_closed_supply_switches_give_a_loop_through_the_supply_rail(self) -> None:
        high_side_brake = figures.Mode('High-side brake', frozenset({'Q1', 'Q3'}))
        current = figures.current_of(high_side_brake)
        self.assertIs(current, figures.Current.SUPPLY_LOOP)
        panel = figures.BRIDGE_LAYOUTS[0].panel(0)
        path = figures.current_path(panel, current)
        self.assertEqual(switches_on_a_path(panel, path), set(high_side_brake.closed))
        self.assertTrue(passes_the_motor(panel, path))

    def test_a_mode_with_a_floating_terminal_has_no_current(self) -> None:
        for closed in ('Q1', 'Q2', 'Q3', 'Q4'):
            one_switch_closed = figures.Mode(f'Only {closed}', frozenset({closed}))
            self.assertIs(figures.current_of(one_switch_closed), figures.Current.NONE, closed)

    def test_the_pages_table_closes_the_same_switches_as_the_figure(self) -> None:
        rows = {row['mode']: row['closed'].strip()
                for row in MODE_ROW.finditer(PAGE.read_text(encoding='utf-8'))}
        self.assertEqual(sorted(rows), sorted(mode.name for mode in figures.MODES))
        for mode in figures.MODES:
            named = set(re.findall(r'Q\d', rows[mode.name]))
            self.assertEqual(named, set(mode.closed), mode.name)


class TestDrawnBridge(unittest.TestCase):
    """Each panel of the generated H-bridge drawing shows the circuit of its mode.

    The tests read the drawing's SVG, in both layouts: what a reader sees, not what the script
    calculates on the way.
    """

    def setUp(self) -> None:
        self.bridges = [(layout.css_class, bridge) for layout in figures.BRIDGE_LAYOUTS
                        for bridge in drawn_bridges(layout)]

    def test_each_layout_draws_one_panel_for_each_mode_of_table_1(self) -> None:
        for layout in figures.BRIDGE_LAYOUTS:
            modes = [bridge.mode for bridge in drawn_bridges(layout)]
            self.assertEqual(modes, list(AN905_TABLE_1), layout.css_class)

    def test_each_panel_draws_closed_levers_only_for_the_switches_in_table_1(self) -> None:
        for layout_class, bridge in self.bridges:
            self.assertEqual(set(bridge.levers), SWITCH_NAMES, (layout_class, bridge.mode))
            self.assertEqual(bridge.closed, AN905_TABLE_1[bridge.mode],
                             (layout_class, bridge.mode))

    def test_the_closed_levers_and_no_others_have_the_bold_stroke(self) -> None:
        for layout_class, bridge in self.bridges:
            bold = {name for name, lever in bridge.levers.items() if lever.bold}
            self.assertEqual(bold, bridge.closed, (layout_class, bridge.mode))

    def test_the_line_under_each_title_names_the_levers_that_are_closed(self) -> None:
        for layout_class, bridge in self.bridges:
            line = only(label.text for label in bridge.labels
                        if label.text.endswith(' closed') or label.text == 'all open')
            expected = f"{' and '.join(sorted(bridge.closed))} closed"
            self.assertEqual(line, expected if bridge.closed else 'all open',
                             (layout_class, bridge.mode))

    def test_the_highlighted_path_passes_the_motor_and_exactly_the_closed_levers(self) -> None:
        for layout_class, bridge in self.bridges:
            if not AN905_TABLE_1[bridge.mode]:
                self.assertEqual(bridge.highlighted_paths, [], (layout_class, bridge.mode))
                continue
            path = only(bridge.highlighted_paths)
            passed = {name for name in bridge.levers
                      if runs_between(path, *bridge.contacts_of(name))}
            self.assertEqual(passed, bridge.closed, (layout_class, bridge.mode))
            self.assertTrue(crosses(path, bridge.motor), (layout_class, bridge.mode))

    def test_each_panel_names_its_upper_rail_v_and_its_lower_rail_gnd(self) -> None:
        for layout_class, bridge in self.bridges:
            upper_rail, lower_rail = bridge.rails
            supply_name = only(label for label in bridge.labels if label.text == '+V')
            ground_name = only(label for label in bridge.labels if label.text == 'GND')
            self.assertTrue(upper_rail.y1 - RAIL_NAME_REACH < supply_name.y <= upper_rail.y1,
                            (layout_class, bridge.mode))
            self.assertTrue(lower_rail.y1 < ground_name.y <= lower_rail.y1 + RAIL_NAME_REACH,
                            (layout_class, bridge.mode))

    def test_a_drive_panels_highlighted_path_runs_from_the_upper_rail_to_the_lower_rail(
            self) -> None:
        for layout_class, bridge in self.bridges:
            if bridge.mode not in DRIVE_MODES:
                continue
            upper_rail, lower_rail = bridge.rails
            path = only(bridge.highlighted_paths)
            self.assertEqual((path[0].y1, path[-1].y2), (upper_rail.y1, lower_rail.y1),
                             (layout_class, bridge.mode))

    def test_only_a_drive_panel_has_an_arrowhead_and_it_points_toward_the_grounded_side(
            self) -> None:
        for layout_class, bridge in self.bridges:
            if bridge.mode not in DRIVE_MODES:
                self.assertEqual(bridge.arrowheads, [], (layout_class, bridge.mode))
                continue
            # Of a drive mode's two closed levers, the upper one connects its side to +V and
            # the lower one connects the other side to ground
            to_supply, to_ground = sorted((bridge.levers[name].piece for name in bridge.closed),
                                          key=lambda lever: lever.y1)
            heading = math.copysign(1, to_ground.x1 - to_supply.x1)
            # The arrowhead's path starts at one end of its base and runs to its tip first
            base_to_tip = only(bridge.arrowheads)[0]
            self.assertGreater((base_to_tip.x2 - base_to_tip.x1) * heading, 0,
                               (layout_class, bridge.mode))
            # The arrowhead stands outside the motor's circle, where the current leaves it
            self.assertGreater((base_to_tip.x1 - bridge.motor.x) * heading, bridge.motor.radius,
                               (layout_class, bridge.mode))

    def test_each_panels_wires_join_the_rails_the_contacts_and_the_motor(self) -> None:
        for layout_class, bridge in self.bridges:
            upper_rail, lower_rail = bridge.rails
            left_x, right_x = bridge.half_bridge_xs
            motor = bridge.motor
            expected = {Segment(left_x, motor.y, motor.x - motor.radius, motor.y),
                        Segment(motor.x + motor.radius, motor.y, right_x, motor.y)}
            for half_bridge_x in (left_x, right_x):
                first, second, third, fourth = sorted(
                    contact.y for contact in bridge.contacts if contact.x == half_bridge_x)
                # The motor's terminal lies between the two switches of its half-bridge
                self.assertTrue(second < motor.y < third, (layout_class, bridge.mode))
                expected |= {Segment(half_bridge_x, upper_rail.y1, half_bridge_x, first),
                             Segment(half_bridge_x, second, half_bridge_x, third),
                             Segment(half_bridge_x, fourth, half_bridge_x, lower_rail.y1)}
            self.assertEqual(set(bridge.wires), expected, (layout_class, bridge.mode))
            for rail in bridge.rails:
                self.assertEqual((rail.x1, rail.x2), (left_x, right_x),
                                 (layout_class, bridge.mode))

    def test_each_panel_marks_its_motor_with_the_letter_m(self) -> None:
        for layout_class, bridge in self.bridges:
            letter = only(label for label in bridge.labels if label.text == 'M')
            self.assertTrue(bridge.motor.holds(letter.x, letter.y), (layout_class, bridge.mode))


