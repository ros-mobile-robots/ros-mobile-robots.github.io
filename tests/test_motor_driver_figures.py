class TestDrawnPwm(unittest.TestCase):
    """Each row of the generated PWM drawing shows its duty cycle, in both layouts.

    The tests read the drawing's SVG and compare it with EXPECTED_ROWS, which is calculated
    by hand.
    """

    def setUp(self) -> None:
        self.drawings = [(layout.css_class, ElementTree.fromstring(figures.pwm_figure(layout)))
                         for layout in figures.PWM_LAYOUTS]

    def test_each_layout_draws_the_three_rows_with_their_texts(self) -> None:
        for layout_class, drawing in self.drawings:
            texts = [(row.duty_label.text, row.command_label.text, row.average_label.text)
                     for row in drawn_rows(drawing)]
            self.assertEqual(texts, [(row.duty_label, row.command_label, row.average_label)
                                     for row in EXPECTED_ROWS], layout_class)

    def test_each_rows_voltage_is_high_for_its_duty_cycle_share_of_every_period(self) -> None:
        for layout_class, drawing in self.drawings:
            rows = drawn_rows(drawing)
            self.assertEqual(len(rows), len(EXPECTED_ROWS), layout_class)
            for row, expected in zip(rows, EXPECTED_ROWS):
                self.assertEqual(len(row.pulses), PERIODS_PER_ROW, (layout_class, expected))
                period_width = (row.end_x - row.start_x) / PERIODS_PER_ROW
                for index, pulse in enumerate(row.pulses):
                    self.assertAlmostEqual(pulse.x1, row.start_x + index * period_width,
                                           COORDINATE_PLACES, (layout_class, expected))
                    self.assertAlmostEqual((pulse.x2 - pulse.x1) / period_width, expected.duty,
                                           COORDINATE_PLACES, (layout_class, expected))

    def test_each_rows_average_line_lies_at_its_duty_cycle_share_of_the_supply_level(
            self) -> None:
        for layout_class, drawing in self.drawings:
            rows = drawn_rows(drawing)
            self.assertEqual(len(rows), len(EXPECTED_ROWS), layout_class)
            for row, expected in zip(rows, EXPECTED_ROWS):
                line = row.average_line
                self.assertAlmostEqual(
                    (row.zero_level - line.y1) / (row.zero_level - row.supply_level),
                    expected.duty, COORDINATE_PLACES, (layout_class, expected))
                self.assertEqual((line.x1, line.x2, line.y2), (row.start_x, row.end_x, line.y1),
                                 (layout_class, expected))

    def test_every_row_starts_right_of_its_texts_and_ends_inside_the_drawing(self) -> None:
        for layout_class, drawing in self.drawings:
            drawing_width = float(drawing.get('viewBox', '').split()[2])
            rows = drawn_rows(drawing)
            for row in rows:
                # The two texts left of a wave end at their x
                self.assertLess(max(row.duty_label.x, row.command_label.x), row.start_x,
                                layout_class)
                self.assertLess(row.end_x, drawing_width, layout_class)
            self.assertEqual(len({(row.start_x, row.end_x) for row in rows}), 1, layout_class)

    def test_the_bracket_under_the_rows_spans_one_period_and_names_its_length(self) -> None:
        for layout_class, drawing in self.drawings:
            rows = drawn_rows(drawing)
            first_rise, second_rise = rows[0].pulses[0].x1, rows[0].pulses[1].x1
            bracket = only(drawn_paths(drawing, 'dimension'))[0]
            self.assertEqual((bracket.x1, bracket.x2), (first_rise, second_rise), layout_class)
            self.assertGreater(bracket.y1, rows[-1].zero_level, layout_class)
            name = only(label for label in drawn_labels(drawing)
                        if label.text.startswith('One period'))
            self.assertEqual(name.text,
                             f'One period T ≈ {PERIOD_AT_THE_HIGHEST_FREQUENCY_MS:.2f} ms',
                             layout_class)
            self.assertAlmostEqual(name.x, (first_rise + second_rise) / 2, COORDINATE_PLACES,
                                   layout_class)
            self.assertGreater(name.y, bracket.y1, layout_class)

    def test_the_caption_names_the_rows_commands_duty_cycles_and_averages(self) -> None:
        caption = only(re.findall(r'<figcaption>(.*?)</figcaption>', figures.pwm_include()))
        commands = [row.command_label.replace('command ', '') for row in EXPECTED_ROWS]
        averages = [row.average_label.replace('average ', '') for row in EXPECTED_ROWS]
        for expected in (
                f'an ideal supply of {NOMINAL_PACK_VOLTAGE:.1f} V',
                f'the commands {figures.listed(commands)} apply the voltage for '
                f'{figures.listed([row.duty_label for row in EXPECTED_ROWS])} of the period',
                f'the averages, {figures.listed(averages)}.',
                f'lasts about {PERIOD_AT_THE_HIGHEST_FREQUENCY_MS:.2f} ms'):
            self.assertIn(expected, caption)

    def test_the_supply_voltage_stands_over_the_first_pulse_and_0_v_under_the_first_gap(
            self) -> None:
        for layout_class, drawing in self.drawings:
            first_row, second_row = drawn_rows(drawing)[:2]
            labels = drawn_labels(drawing)
            supply_name = only(label for label in labels
                               if label.text == f'{NOMINAL_PACK_VOLTAGE:.1f} V')
            zero_name = only(label for label in labels if label.text == '0 V')
            first_pulse, first_gap = first_row.pulses[0], first_row.gaps[0]
            self.assertTrue(first_pulse.x1 <= supply_name.x <= first_pulse.x2, layout_class)
            self.assertLess(supply_name.y, first_row.supply_level, layout_class)
            self.assertTrue(first_gap.x1 <= zero_name.x <= first_gap.x2, layout_class)
            self.assertTrue(first_row.zero_level < zero_name.y < second_row.supply_level,
                            layout_class)


class TestPage(unittest.TestCase):
    """The page's text repeats the numbers that the script calculates."""

    def setUp(self) -> None:
        self.page = PAGE.read_text(encoding='utf-8')

    def test_the_duty_table_gives_the_figures_commands_and_the_highest_command(self) -> None:
        rows = [(int(row['command']), int(row['counts']), row['duty'])
                for row in DUTY_ROW.finditer(self.page)]
        expected = [(pulse.command, pulse.counts, figures.percent(pulse.duty))
                    for pulse in figures.pulses() + (figures.pulse_of(figures.MAX_COMMAND),)]
        self.assertEqual(rows, expected)

